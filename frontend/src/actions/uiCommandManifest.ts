/**
 * ONE HTTP CALL THE SHIPPED CLIENT MAKES — the join key the Go registry needs.
 *
 * ⛔ THIS IS THE FIELD W0's COVERAGE GATE RUNS ON, AND ITS SHAPE IS NOT
 * NEGOTIABLE: (verb, path). internal/server's generator hands the path to chi's
 * own `Find` and keeps the PATTERN the router returns, so both halves of the
 * gate speak the router's spelling of route identity and no second one can
 * arise. Deriving an ACL key from a screen kind instead is wrong on at least six
 * screens in this product — `tds-challans` is governed by the SINGULAR bare
 * token `tds-challan`, `print-templates` is `company` and not a report at all —
 * and wrong in the direction that looks plausible.
 *
 * `used` is the honest qualifier on the claim. A method the REST client exposes
 * but nothing in the app calls does NOT put a human in front of the route; ten
 * of the 159 are in that state today, and the Go side keeps them at channel
 * "none" so they surface as unreachable actions rather than being counted as
 * covered.
 *
 * ⛔ WHAT THIS MANIFEST STILL DOES NOT EMIT, AND MUST NOT BE READ AS EMITTING: A
 * KEYSTROKE-LEVEL CLAIM. No {@link UICommand} carries an `acl` field, so
 * internal/actions' generator — which reads `commands[].acl` and PREFERS it over
 * this census when a command has one (see the ChannelClient comment in
 * internal/actions/spec.go) — finds nothing here to prefer, and every route a
 * client method reaches is graded `client`: "somebody driving this product
 * reaches it", never "F9 on the Sales voucher reaches it". That is the remaining
 * half of W0 D3 and it is OWED, not done. Nothing in this file should be read as
 * having discharged it.
 *
 * ⚠️ THE SEAM THAT WAS MEANT TO SUPPLY IT HAS BEEN DELETED, ON PURPOSE.
 * app/ScreenActions.tsx carried a third `calls?: readonly (keyof CoredClient)[]`
 * parameter on useRegisterScreenAction, recorded into a module-level Map: no call
 * site ever passed it, nothing ever read it, and it could not have fed this file
 * anyway — it registered from inside a hook, so it held only what was MOUNTED,
 * and this generator runs in a bare Node process where that is the empty set.
 * What WOULD supply the claim is a declaration this module can read without
 * mounting anything: a plain `const` exported from each screen module beside its
 * handler, imported here exactly as AppShell's SCREEN_ACTIONS and
 * GatewayScreen's GATEWAY_MENU already are, and emitted as `acl` on the command
 * whose `screen_action` dispatches to it. That is a couple of dozen screen files
 * and belongs in its own change.
 */
export interface ClientCall {
  /** The CoredClient method name, so a reviewer can grep one string. */
  readonly method: string;
  readonly verb: string;
  /** The path with `{paramName}` placeholders, exactly as the client built it. */
  readonly path: string;
  /** Whether app code outside src/api references the method at all. */
  readonly used: boolean;
}

