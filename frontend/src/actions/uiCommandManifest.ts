/**
 * WHICH (verb, path) EACH CLIENT METHOD ACTUALLY CALLS — measured by CALLING IT.
 *
 * ⛔ THE CLIENT IS DRIVEN, NOT PARSED, AND THAT IS THE SAME DECISION THE REST OF
 * THIS FILE MAKES. `createRestClient` is handed a recording {@link HttpClient}
 * and every method on the object it returns is invoked; what lands in the
 * recorder is the path the client built, character for character, including the
 * ones assembled from a `company(id)` helper and a template literal. A regex or
 * AST scan over rest.ts would have to re-implement that assembly — a second
 * spelling of route identity, which is precisely what the Go side's generator
 * comment forbids — and would go stale in the direction that keeps the gate
 * green.
 *
 * ⚠️ THE ARGUMENTS ARE NAMED PLACEHOLDERS TAKEN FROM THE FUNCTION'S OWN
 * PARAMETER LIST, so `getCompany(companyID)` produces
 * `/v1/companies/{companyID}` rather than `/v1/companies/undefined`. The Go side
 * resolves `{companyID}` to the walk's company id and every other placeholder to
 * a value of the right SHAPE (a uuid, or `0` for `legNo`, which
 * `bankReconLeg` parses with Atoi). If a future build ever minified these
 * parameter names the paths would become `/v1/companies/{a}/…`, the router would
 * fail to match them, and the generator FAILS on the unresolved list — loudly,
 * which is the only acceptable way for this to break.
 *
 * ⚠️ AND SOME METHODS THROW AFTER THEIR CALL. Three payroll methods read
 * `res.header(...)` off the response; a recorder cannot return a real
 * BlobResponse, so they throw — AFTER the request was recorded. The throw is
 * caught and the recorded call kept, because what is being measured is the
 * request, not the response handling. A method that records NOTHING is a
 * different matter and is reported by the caller.
 */
/**
 * EVERY OBJECT IN THIS APP THAT SPEAKS HTTP TO CORED, not just the big one.
 *
 * ⛔ THE SECOND AND THIRD ENTRIES ARE NOT COMPLETENESS FOR ITS OWN SAKE — THEY
 * WERE MEASURED AS A HOLE. With only `createRestClient` driven, the six `/drafts`
 * routes came back as actions no human can reach, and the Bill Inbox screen
 * drives all six every time an operator opens it: the drafts surface is a
 * SEPARATE client (api/insightd.ts) plus three lifecycle POSTs built inside
 * screens/vouchers/draftAccept.ts. A census that knows about one client and
 * reports the others' routes as unreachable does not merely miss coverage, it
 * manufactures findings — and the response to a false finding is to add an
 * exemption, which is how a real one later goes unnoticed.
 *
 * `methods` narrows a surface to the calls that can be driven with a stubbed
 * transport. The draft lifecycle's fourth method, `alreadyAccepted`, reads
 * through an injected insightd client rather than through `deps.http`, and
 * driving it here would either re-record api/insightd.ts's own paths or reach
 * for a real one; its routes are covered by the insightd surface above it.
 */
const CLIENT_SURFACES: readonly {
  readonly name: string;
  readonly build: (http: HttpClient) => Record<string, unknown>;
  readonly methods?: readonly string[];
}[] = [
  { name: "rest", build: (http) => createRestClient({ http }) as unknown as Record<string, unknown> },
  { name: "insightd", build: (http) => createInsightdClient({ http }) as unknown as Record<string, unknown> },
  {
    name: "draft-lifecycle",
    build: (http) => insightdDraftLifecycle({ http }) as unknown as Record<string, unknown>,
    methods: ["claim", "releaseClaim", "recordAccepted"],
  },
];

function clientCalls(): ClientCall[] {
  const recorded: { method: string; verb: string; path: string }[] = [];
  let current = "";
  const record =
    (verb: string) =>
    <T,>(path: string): Promise<T> => {
      recorded.push({
        method: current,
        verb,
        // The client percent-encodes every path segment (ids can be arbitrary
        // strings); decoding gives back the `{name}` the placeholder went in as.
        path: decodeURIComponent(path),
      });
      return Promise.resolve(placeholder("response") as T);
    };
  const http = {
    get: record("GET"),
    post: record("POST"),
    put: record("PUT"),
    del: record("DELETE"),
    postRaw: record("POST"),
    getBlob: record("GET"),
  } as unknown as HttpClient;

  const used = referencedClientMethods();
  const out: ClientCall[] = [];
  const silent: string[] = [];
  for (const surface of CLIENT_SURFACES) {
    const client = surface.build(http) as Record<
      string,
      (...args: unknown[]) => unknown
    >;
    const names = (surface.methods ?? Object.keys(client)).slice().sort();
    for (const method of names) {
      const fn = client[method];
      if (typeof fn !== "function") {
        silent.push(`${surface.name}.${method}`);
        continue;
      }
      current = method;
      const before = recorded.length;
      try {
        // ⚠️ THE .catch IS NOT DECORATION. A method that throws inside its own
        // `.then` produces an UNHANDLED REJECTION, which vitest turns into a
        // failure of the whole run — so one un-modelled response shape would
        // take the entire frontend suite down rather than one census row.
        void Promise.resolve(fn(...parameterNames(fn).map(placeholder))).catch(
          () => undefined,
        );
      } catch {
        // See the note above: the request, if any, is already recorded.
      }
      if (recorded.length === before) silent.push(`${surface.name}.${method}`);
    }
  }
  if (silent.length > 0) {
    // ⛔ NOT A SKIP. A method that makes no HTTP call is either dead weight on
    // the client or a method whose call this census cannot see — and the second
    // reading means the Go coverage gate is blind to whatever route it hits.
    // Neither may be discovered by its absence from a JSON file.
    throw new Error(
      `uiCommandManifest: ${silent.length} CoredClient method(s) made no HTTP ` +
        `call when driven: ${silent.join(", ")}. Either the method is dead, or ` +
        `this census cannot see the call it makes — and in the second case the ` +
        `Go action registry is blind to that route.`,
    );
  }
  const seen = new Set<string>();
  for (const r of recorded) {
    // Two surfaces can legitimately build the same URL; the registry joins on
    // (verb, path), so one row per distinct call is the honest shape.
    const key = `${r.method} ${r.verb} ${r.path}`;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push({ ...r, used: used.has(r.method) });
  }
  return out.sort((a, b) =>
    a.method === b.method
      ? a.verb < b.verb
        ? -1
        : a.verb > b.verb
          ? 1
          : 0
      : a.method < b.method
        ? -1
        : 1,
  );
}

/**
 * A stand-in argument that survives being used as a string, a list or a record.
 *
 * The client's methods interpolate their arguments into a path, read fields off
 * request objects and iterate over collections. One placeholder has to be usable
 * as all three or the census stops at the first method that does something other
 * than string interpolation — which was measured: four of the 159 threw before
 * reaching their call until this became a Proxy.
 *
 * ⚠️ `toString`/`valueOf`/`Symbol.toPrimitive` ARE DEFINED ON THE TARGET. Without
 * them, `${p}` inside a template literal invokes String.prototype.toString with
 * the PROXY as `this` and throws "requires that 'this' be a String" — so every
 * path came back empty. Measured, not anticipated.
 */
function placeholder(name: string): never {
  const value = `{${name}}`;
  // ⚠️ THE TARGET IS A FUNCTION, NOT A STRING OBJECT, so a placeholder can also
  // be CALLED. The three statutory payroll methods do `res.header("X-...")` on
  // what they got back; with a non-callable stand-in that throws inside a
  // `.then`, which surfaces as an unhandled rejection and fails the whole vitest
  // run rather than the one method. Measured.
  const target = function () {
    return placeholder(name);
  } as unknown as Record<string | symbol, unknown>;
  target.toString = () => value;
  target.valueOf = () => value;
  target[Symbol.toPrimitive] = () => value;
  target.map = () => [];
  target[Symbol.iterator] = function* () {};
  return new Proxy(target, {
    get(t, prop, receiver) {
      if (prop in t) return Reflect.get(t, prop, receiver);
      if (typeof prop === "symbol") return undefined;
      return placeholder(String(prop));
    },
  }) as never;
}

/**
 * The parameter names of a function, read off the function itself.
 *
 * `fn.toString()` is the only runtime source of these names, and they are what
 * turn a recorded path into `/v1/companies/{companyID}/ledgers/{ledgerID}` — a
 * shape the Go side can resolve — instead of a string of `undefined`s. Anything
 * that is not a plain identifier (a destructured or defaulted parameter) is
 * reduced to its leading token, which is good enough for a placeholder and never
 * silently wrong: a name the Go side cannot resolve produces a path the router
 * does not match, and the generator fails on it by name.
 */
function parameterNames(fn: (...args: unknown[]) => unknown): string[] {
  const src = fn.toString();
  const open = src.indexOf("(");
  if (open < 0) return [];
  let depth = 0;
  let end = open;
  for (; end < src.length; end++) {
    if (src[end] === "(") depth++;
    else if (src[end] === ")") {
      depth--;
      if (depth === 0) break;
    }
  }
  const inner = src.slice(open + 1, end).trim();
  if (inner === "") return [];
  const parts: string[] = [];
  let nested = 0;
  let cur = "";
  for (const ch of inner) {
    if ("([{".includes(ch)) nested++;
    if (")]}".includes(ch)) nested--;
    if (ch === "," && nested === 0) {
      parts.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  parts.push(cur);
  return parts.map((p) => (p.trim().split(/[=:]/)[0] ?? "").trim());
}

/**
 * Which client methods the APP mentions at all, outside the API layer itself.
 *
 * ⛔ THIS IS THE ONE FACT IN THIS FILE READ FROM SOURCE TEXT RATHER THAN FROM A
 * LIVE OBJECT, AND THE ALTERNATIVE IS WORSE. "Is this method reachable from a
 * screen?" cannot be answered by the objects: it would mean mounting all 37
 * screens and firing every control, i.e. exactly the census-of-what-happens-to-
 * be-mounted this module's header rejects. So it is a MENTION scan — deliberately
 * the most permissive form, because `client.createSalesOrder.bind(client)` is a
 * real use and a call-shaped regex misses it.
 *
 * ⚠️ WHAT IT CAN AND CANNOT BE WRONG ABOUT. It can over-report (a mention inside
 * code nothing renders), so `used: true` means "the app's own source names this
 * method", NOT "a keystroke presses it" — the Go side's ChannelClient says so in
 * those words. It cannot under-report, which is the direction that matters: a
 * method nothing mentions is genuinely unreachable, and the ten it finds today
 * become declared orphans in the Go registry rather than silent coverage.
 *
 * Tests are excluded: a method exercised only by its own unit test is not a
 * method a human can reach.
 */
function referencedClientMethods(): Set<string> {
  const root = join(__dirname, "..");
  const sources: string[] = [];
  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = join(dir, entry.name);
      if (entry.isDirectory()) {
        // src/api is the API layer itself: rest.ts DEFINES these methods and
        // mock.ts mirrors them, so counting either would mark every method used
        // and the scan would report nothing, always.
        if (entry.name === "api" && dir === root) continue;
        walk(full);
        continue;
      }
      if (!/\.tsx?$/.test(entry.name)) continue;
      if (/\.test\.tsx?$/.test(entry.name)) continue;
      sources.push(full);
    }
  };
  walk(root);
  if (sources.length < 50) {
    // The scanned-nothing guard. A walk that found a handful of files would
    // mark every client method unused and quietly turn 150 covered actions into
    // declared orphans.
    throw new Error(
      `uiCommandManifest: the client-usage scan found only ${sources.length} ` +
        `source files under ${root}; that is not this app and the manifest it ` +
        `would produce is wrong in the direction that hides coverage.`,
    );
  }
  const blob = sources.map((f) => readFileSync(f, "utf8")).join("\n");
  const mentioned = new Set<string>();
  for (const m of blob.matchAll(/\b[A-Za-z_$][A-Za-z0-9_$]*\b/g)) {
    mentioned.add(m[0]);
  }
  return mentioned;
}

/** Build the manifest from the live keymap, shell, Gateway, registry and client. */
export function buildUICommandManifest(): UICommandManifest {
  const commands = [
    ...globalCommands(),
    ...screenCommands(),
    ...gatewayCommands(),
  ].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

  const keys = routeKeys();
  const routes = clientRoutes();
  const calls = clientCalls();

  return {
    note:
      "GENERATED ARTEFACT — do not hand-edit. Emitted by " +
      "src/actions/uiCommandManifest.ts and COMPARED (not written) by its test. " +
      "Regenerate with: UPDATE_UI_MANIFEST=1 pnpm run test:run -- uiCommandManifest",
    keymap_profile: tallyPrimeKeymap.profile,
    counts: {
      screen_kinds: SCREEN_KINDS.length,
      route_keys: keys.length,
      commands: commands.length,
      global_bindings: commands.filter((c) => c.surface === "keymap-global")
        .length,
      screen_scoped_bindings: commands.filter(
        (c) => c.surface === "keymap-screen",
      ).length,
      gateway_entries: commands.filter((c) => c.surface === "gateway-menu")
        .length,
      client_routes: routes.length,
      client_calls: calls.length,
      unused_client_methods: new Set(
        calls.filter((c) => !c.used).map((c) => c.method),
      ).size,
      dead_commands: commands.filter((c) => c.dispatch === "dead").length,
    },
    screen_kinds: SCREEN_KINDS,
    route_keys: keys,
    commands,
    client_routes: routes,
    client_calls: calls,
  };
}

/**
 * The manifest's on-disk form. Two spaces and a trailing newline, so a
 * regeneration produces a reviewable diff rather than one very long line.
 */
export function renderUICommandManifest(): string {
  return `${JSON.stringify(buildUICommandManifest(), null, 2)}\n`;
}
