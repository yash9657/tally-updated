/** Where a command is offered to the operator. */
export type CommandSurface = "keymap-global" | "keymap-screen" | "gateway-menu";

/**
 * WHAT HAPPENS WHEN THE OPERATOR FIRES IT. This is the field the census is for.
 *
 * - `screen-action`  the AppShell finds a SCREEN_ACTIONS entry and fires the
 *                    screen's registered handler (AppShell.tsx:409-411).
 * - `machine`        the navigation machine moves the stack for it.
 * - `unavailable`    the keymap binds it to an explicit refusal with a note, so
 *                    the operator is told the feature is not in this edition.
 * - `dead`           NONE OF THE ABOVE. The shell resolves the combo, finds no
 *                    screen action, forwards it to a machine with no case for
 *                    it, observes an unchanged stack and prints
 *                    "<combo> — <label> does not apply on this screen."
 *                    The key looks bound in every review and does nothing.
 */
export type CommandDispatch =
  | "screen-action"
  | "machine"
  | "unavailable"
  | "dead";

/** One thing a person can do, and how the app answers it. */
export interface UICommand {
  /** Stable identity for the Go coverage gate to key on. */
  readonly id: string;
  readonly surface: CommandSurface;
  /** "*" for a global binding, a ScreenKind for an override, "gateway" for a door. */
  readonly scope: string;
  /** The NORMALISED combo (normalizeCombo's output), or null for a menu door. */
  readonly combo: string | null;
  /** The KeymapAction kind this resolves to, or null for a menu door. */
  readonly action: string | null;
  /** What the operator is told this key does (Help screen + status line prose). */
  readonly label: string;
  /** The ScreenActionKind the shell dispatches, if any. */
  readonly screen_action: string | null;
  readonly dispatch: CommandDispatch;
}

