/**
 * THREE STACKS TO ASK THE QUESTION ON, AND ALL THREE ARE LOAD-BEARING.
 *
 * The census asks "is there ANY stack on which the machine moves for this key?".
 * A single probe stack turns that into an accidental question, and every one of
 * these three was added because a working key came back DEAD against the
 * previous set — measured, not anticipated:
 *
 *  1. `shallow` — the screen alone, as `makeInitialContext` builds it.
 *  2. `deep` — a Gateway underneath it, and a `selectedItem` on top. `escape`
 *     and `quit` POP a frame, so on a one-frame stack they correctly do nothing,
 *     and `enter` DRILLS a pick, so it does nothing until there is one. Without
 *     this stack the three load-bearing navigation keys all read as dead.
 *  3. `worked` — a voucher frame that has been SAVED and re-opened for
 *     ALTERATION, with the field cursor moved off the first field. `editLog`
 *     (Alt+L) refuses anything but `voucherMode === "alter"`; `duplicate` and
 *     `delete` do the same; and `date` (F2) MOVES THE CURSOR TO THE DATE FIELD —
 *     which is where `makeInitialContext` already parks it, so F2 produced a
 *     byte-identical stack and the voucher date key read as dead.
 *
 * ⚠️ THE EXTRA FIELDS ARE SET ON EVERY SCREEN, NOT JUST ON VOUCHERS. Nothing is
 * pretending a Balance Sheet has a voucher mode: every reducer arm that reads
 * `voucherMode` guards on `screen === "voucher"` first, so the field is inert
 * elsewhere — and a per-screen special case here would be a second table of
 * which screens are voucher-like, which is the drift this census exists to find.
 */
function probeContexts(screen: ScreenKind): NavContext[] {
  const shallow = makeInitialContext({ startScreen: screen });
  const frame = shallow.stack[shallow.stack.length - 1] as ScreenFrame;
  const deep: NavContext = {
    ...shallow,
    stack: [{ screen: "gateway" }, { ...frame, selectedItem: "Day Book" }],
  };
  const worked: NavContext = {
    ...shallow,
    stack: [
      { screen: "gateway" },
      {
        ...frame,
        voucherMode: "alter",
        saved: true,
        field: "narration",
        selectedItem: "Day Book",
      },
    ],
  };
  return [shallow, deep, worked];
}

/**
 * Does the REAL navigation machine move for this combo on this screen?
 *
 * ⛔ IT CALLS `keyChangesStack`, WHICH CALLS THE REAL `reduceKey`. A census that
 * re-implemented "which actions the machine handles" as a list would be a second
 * table of route identity, and it would go stale in the direction that keeps the
 * gate green: an action deleted from the reducer stays on the list and the dead
 * key it leaves behind is never reported.
 */
function machineMoves(screen: ScreenKind, combo: string): boolean {
  return probeContexts(screen).some((ctx) => keyChangesStack(ctx, combo));
}

/**
 * Classify one binding.
 *
 * `screens` is the set of screens the binding is asked about: the single screen
 * for an override, and — for a GLOBAL binding — every screen that does not
 * itself override the combo.
 *
 * ⚠️ THAT EXCLUSION IS LOAD-BEARING AND EASY TO MISS. `reduceKey` resolves the
 * combo through `resolveAction(keymap, activeScreen, combo)`, so probing the
 * global F4 on the `gstr9` screen actually exercises that screen's
 * `selectFinancialYear` override. Without the filter a global binding would be
 * declared alive on the strength of a DIFFERENT action bound to the same key
 * somewhere else — the precise shape of a green gate that checks nothing.
 */
function classify(
  action: KeymapAction,
  combo: string,
  screens: readonly ScreenKind[],
): { dispatch: CommandDispatch; screenAction: string | null } {
  if (action.kind === "unavailable") {
    return { dispatch: "unavailable", screenAction: null };
  }
  const screenAction = SCREEN_ACTIONS[action.kind] ?? null;
  if (screenAction) return { dispatch: "screen-action", screenAction };
  for (const screen of screens) {
    if (machineMoves(screen, combo)) {
      return { dispatch: "machine", screenAction: null };
    }
  }
  return { dispatch: "dead", screenAction: null };
}

/** The global table: one command per binding, scoped "*". */
function globalCommands(): UICommand[] {
  const overrides = tallyPrimeKeymap.screenBindings ?? {};
  const out: UICommand[] = [];
  for (const [combo, action] of Object.entries(tallyPrimeKeymap.bindings)) {
    const screens = SCREEN_KINDS.filter(
      (s) => overrides[s]?.[combo] === undefined,
    );
    const { dispatch, screenAction } = classify(action, combo, screens);
    out.push({
      id: `key:*:${combo}`,
      surface: "keymap-global",
      scope: "*",
      combo,
      action: action.kind,
      label: actionLabel(action),
      screen_action: screenAction,
      dispatch,
    });
  }
  return out;
}

/** The per-screen override tables: one command per (screen, combo). */
function screenCommands(): UICommand[] {
  const out: UICommand[] = [];
  for (const screen of SCREEN_KINDS) {
    const table = tallyPrimeKeymap.screenBindings?.[screen];
    if (!table) continue;
    for (const [combo, action] of Object.entries(table)) {
      const { dispatch, screenAction } = classify(action, combo, [screen]);
      out.push({
        id: `key:${screen}:${combo}`,
        surface: "keymap-screen",
        scope: screen,
        combo,
        action: action.kind,
        label: actionLabel(action),
        screen_action: screenAction,
        dispatch,
      });
    }
  }
  return out;
}

/**
 * The Gateway of Tally doors.
 *
 * ⛔ THESE ARE DRIVEN BY *SELECT*, NOT BY A KEY, SO THEY NEED THEIR OWN ORACLE —
 * the real machine, actually started and actually sent the label. A Gateway entry
 * that navigates nowhere is not hypothetical: the "Reconciliation" label opened
 * the BANK reconciliation screen for two browser runs because the Gateway is
 * driven by typing into a search box and the short name was a substring of a
 * shipped one (see RECONCILIATION_LABEL in navMachine.ts). A door that goes
 * nowhere and a door that goes somewhere WRONG both need the label to be walked,
 * not read.
 */
function gatewayCommands(): UICommand[] {
  return GATEWAY_MENU.map((label) => {
    const actor = createActor(navMachine, {
      input: { startScreen: "gateway" },
    }).start();
    const before = JSON.stringify(actor.getSnapshot().context.stack);
    actor.send({ type: "SELECT", menuItem: label });
    const after = JSON.stringify(actor.getSnapshot().context.stack);
    actor.stop();
    return {
      id: `menu:gateway:${label}`,
      surface: "gateway-menu" as const,
      scope: "gateway",
      combo: null,
      action: null,
      label,
      screen_action: null,
      dispatch: (after === before ? "dead" : "machine") as CommandDispatch,
    };
  });
}

/**
 * Which screens the registry can actually put a component in front of.
 *
 * ⚠️ PROBED THROUGH `resolve`, THE SAME FUNCTION THE SHELL CALLS, rather than by
 * reading the registry's private map. The map's keys say what was registered;
 * `resolve` says what an operator would SEE, and those differ for reports —
 * `report:Day Book` falls back to the generic `report` component when no named
 * entry exists. A named row is emitted only where the resolved component
 * actually differs from that fallback, so the manifest never claims a bespoke
 * screen for a report that renders "not available in this build".
 */
function routeKeys(): RouteKey[] {
  const registry = createDefaultRegistry();
  const probe = (screen: ScreenKind, reportName?: string) =>
    registry.resolve({
      screen,
      screenStackDepth: 1,
      canReturnToVoucher: false,
      ...(reportName ? { reportName } : {}),
    } as NavSnapshot);

  const out: RouteKey[] = SCREEN_KINDS.map((screen) => ({
    key: screen,
    registered: probe(screen) !== undefined,
  }));

  for (const screen of ["report", "report-detail"] as const) {
    const generic = probe(screen);
    for (const name of REPORT_NAMES) {
      const named = probe(screen, name);
      if (named !== undefined && named !== generic) {
        out.push({ key: `${screen}:${name}`, registered: true });
      }
    }
  }
  return out.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
}

