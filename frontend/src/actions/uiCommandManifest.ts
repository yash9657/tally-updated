/**
 * THE UI-COMMAND MANIFEST — the HUMAN half of the W0 D3 coverage gate.
 *
 * The Go side (internal/actions) enumerates what an AGENT may do: an ActionSpec
 * per (authz.Action, authz.Resource) arm, generated by walking the real chi
 * router. This file enumerates what a PERSON may do: every keystroke this app
 * binds, every Gateway door, and where each one is dispatched. The coverage gate
 * compares the two — an agent that can reach a capability no keyboard operator
 * can reach (or the reverse) is a product with two different answers to "what
 * can be done to these books", and the whole premise of a keystroke-compatible
 * ERP is that there is exactly one.
 *
 * ⛔ IT IS DERIVED FROM THE LIVE OBJECTS, NEVER PARSED FROM SOURCE, AND THAT IS
 * THE LOAD-BEARING DECISION. 108 of the screen-scoped bindings DO NOT EXIST AS
 * SOURCE TEXT: they are produced at module load by the
 * `...voucherKeysHeldBack(screen, what)` spread in keymaps/tallyprime.ts, which
 * synthesises twelve `unavailable` bindings for each of nine form-bearing
 * screens. A grep- or AST-based census reads the spread as ONE line and reports
 * roughly half the board — silently, with every test green, because there is
 * nothing for it to disagree with. Combos are also canonicalised by
 * `normalizeCombo` at module load ("Ctrl+a" -> "Ctrl+A", KeyCombo is `= string`
 * and not a union, so nothing in the type system would catch the drift), and the
 * manifest records the NORMALISED form so the Go side never re-derives it.
 *
 * ⚠️ THIS MODULE IS PURE — no JSX, no hooks, no rendering. It imports React
 * modules (AppShell, GatewayScreen, defaultScreens) only to read the DATA they
 * export. Mounting screens to discover their commands is the trap this file
 * exists to avoid: a census that can only see what is currently mounted reports
 * the empty set on a machine where a screen failed to render.
 */

