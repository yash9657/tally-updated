//
//	GET /v1/companies/{companyID}/print/vouchers/{class}/{voucherID}
//	GET /v1/companies/{companyID}/print/reports/{reportName}
//
// It is an IN-PACKAGE test (package server, not server_test) for two reasons:
// routeAction, isVoucherClass and pdfFilename are unexported enforcement wiring,
// and the payroll fixture below needs s.payroll to lay down a salary structure
// that has no HTTP surface in this wave. The in-package HTTP helpers
