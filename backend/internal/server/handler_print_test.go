// mintTokenNoStepUp mints a token with NO amr, i.e. HasWebAuthn() false.
func mintTokenNoStepUp(t *testing.T, s *Server, subject string) string {
	t.Helper()
	rec, body := aclRequest(t, s, http.MethodPost, "/auth/token", "", map[string]any{
		"subject": subject,
	})
	if rec.Code != http.StatusOK {
		t.Fatalf("mint no-step-up token = %d, want 200 (%s)", rec.Code, rec.Body.String())
	}
	tok, _ := body["token"].(string)
	if tok == "" {
		t.Fatalf("mint no-step-up token returned nothing (%s)", rec.Body.String())
	}
	return tok
}

// printGet issues one authenticated GET and returns the recorder, so the raw PDF
// bytes are available (aclRequest only decodes JSON bodies).
func printGet(t *testing.T, s *Server, path, token string) *httptest.ResponseRecorder {
	t.Helper()
	req := httptest.NewRequest(http.MethodGet, path, nil)
	req.Header.Set("Authorization", "Bearer "+token)
	rec := httptest.NewRecorder()
	s.Router().ServeHTTP(rec, req)
	return rec
}

// pdfLines returns the response's extracted text CELL BY CELL, in the order the
// renderer drew it: printing.ExtractText emits one string per show-text operand,
// and drawRow draws one operand per non-empty cell, left column to right column,
// row by row. So the slice is the document's reading order, and a CONTIGUOUS RUN
// of it is a row with its columns in order — which is the only thing that can
// catch a swapped, dropped or reordered column, since an assertion that merely
// greps the whole document for a figure passes whichever column it came from.
//
// AN EMPTY CELL DRAWS NOTHING (reportDrawCell returns early on ""), so a blank
// credit column contributes no element at all. Expected runs must be built the
// same way — see trialBalanceRowRuns.
func pdfLines(t *testing.T, rec *httptest.ResponseRecorder, what string) []string {
	t.Helper()
	if got := rec.Header().Get("Content-Type"); got != "application/pdf" {
		t.Fatalf("%s: Content-Type = %q, want application/pdf (body %.300s)", what, got, rec.Body.String())
	}
	body := rec.Body.Bytes()
	if !strings.HasPrefix(string(body), "%PDF-") {
		t.Fatalf("%s: the body does not begin with the PDF magic; it is not a PDF at all (%.60q)", what, body)
	}
	lines, err := printing.ExtractText(body)
	if err != nil {
		t.Fatalf("%s: the generated bytes are not parseable as a PDF: %v", what, err)
	}
	return lines
}

// pdfText renders the response as extracted text, failing if it is not a PDF.
func pdfText(t *testing.T, rec *httptest.ResponseRecorder, what string) string {
	t.Helper()
	return strings.Join(pdfLines(t, rec, what), "\n")
}

// ---------------------------------------------------------------------------
// WHERE ON THE PAGE A CELL WAS DRAWN.
//
// printing.ExtractText returns the text and nothing else, and for a table of
// figures that is not enough: A BLANK CELL DRAWS NOTHING, so a Trial Balance row
// whose ledger sits on ONE side extracts to the same sequence of strings whether
// its figure was drawn in the debit column or the credit column. Every assertion
// built on the extracted sequence alone is therefore BLIND to the swap it claims
// to catch on the body rows — the extracted text is identical either way.
//
// The x coordinate is not. Every figure column is right-aligned (page.TextRight),
// so a figure drawn in the wrong column lands at a different x, and the
// coordinate is in the content stream beside the text. The helpers below read it
// back.
//
// A COORDINATE IN POINTS IS LEGITIMATELY float64: it is paper geometry, not an
// amount. Nothing derived from a rupee figure is a float anywhere in this file.
// ---------------------------------------------------------------------------

// drawnCell is one show-text operator as the generated PDF carries it: the string
// that was drawn, the font and size it was set in, and WHERE.
type drawnCell struct {
	font printing.Font
	size float64 // points
	x, y float64 // the text-matrix translation, i.e. the LEFT edge and the baseline
	text string
}

// rightEdge is where the cell's text ENDS on the page. It is the invariant a
// right-aligned column is defined by: reportDrawCell sets a figure with
// TextRight(x1), so every figure in one column shares a right edge, and two
// figures with different right edges are in different columns whatever their
// text says.
func (c drawnCell) rightEdge() float64 {
	return c.x + printing.Measure(c.font, c.size, c.text)
}

// pdfFontByResourceName maps the /Font resource key back to the Font that emitted
// it. The table is fixed in printing/font.go (resourceName), never generated, so
// this cannot drift silently — and pdfDrawnCells cross-checks its whole parse
// against printing.ExtractText, which would fail if it did.
var pdfFontByResourceName = map[string]printing.Font{
	"F1": printing.Helvetica,
	"F2": printing.HelveticaBold,
	"F3": printing.HelveticaOblique,
	"F4": printing.Courier,
	"F5": printing.CourierBold,
}

// pdfDrawnCells returns every cell the document drew, WITH its position, in
// drawing order.
//
// It parses the one text-operator shape printing.Page.Text emits:
//
//	BT /F2 8.5 Tf 1 0 0 1 123.4 567.8 Tm (Some text) Tj ET
//
// and it is honest about being that narrow: the streams are uncompressed and the
// shape is fixed, which is the same pair of facts printing.ExtractText relies on.
//
// THE PARSE IS CROSS-CHECKED against printing.ExtractText: the sequence of texts
// must be identical. That is what makes the coordinates trustworthy — a parser
// that silently skipped an operator would otherwise let a column-position
// assertion pass by not looking at the cell that moved.
func pdfDrawnCells(t *testing.T, rec *httptest.ResponseRecorder, what string) []drawnCell {
	t.Helper()
	want := pdfLines(t, rec, what)
	body := rec.Body.Bytes()

	var out []drawnCell
	for i := 0; i+3 < len(body); i++ {
		if body[i] != 'B' || body[i+1] != 'T' || body[i+2] != ' ' || body[i+3] != '/' {
			continue
		}
		cell, ok := parseDrawnCell(body[i:])
		if !ok {
			// Not a text operator after all — "BT /" inside a string literal, say.
			// Skipped rather than fatal, because the cross-check below is what
			// decides whether this parse is complete.
			continue
		}
		out = append(out, cell)
	}

	if len(out) != len(want) {
		t.Fatalf("%s: this test read back %d positioned cells but printing.ExtractText found %d "+
			"text operators. The two disagree, so no assertion about WHICH COLUMN a figure was "+
			"drawn in can be trusted — parseDrawnCell is out of step with printing.Page.Text's "+
			"emission shape", what, len(out), len(want))
	}
	for i := range out {
		if out[i].text != want[i] {
			t.Fatalf("%s: positioned cell %d is %q where printing.ExtractText read %q: the "+
				"coordinate parse and the text parse are looking at different operators, so a "+
				"column-position assertion would be checking the wrong cell",
				what, i, out[i].text, want[i])
		}
	}
	return out
}

// parseDrawnCell reads one `BT /Fn size Tf 1 0 0 1 x y Tm (text) Tj ET` operator
// off the front of b, returning false if b does not begin with exactly that.
func parseDrawnCell(b []byte) (drawnCell, bool) {
	s := string(b)
	rest, ok := cutPrefix(s, "BT /")
	if !ok {
		return drawnCell{}, false
	}
	name, rest, ok := cutField(rest, ' ')
	if !ok {
		return drawnCell{}, false
	}
	font, known := pdfFontByResourceName[name]
	if !known {
		return drawnCell{}, false
	}
	sizeTok, rest, ok := cutField(rest, ' ')
	if !ok {
		return drawnCell{}, false
	}
	rest, ok = cutPrefix(rest, "Tf 1 0 0 1 ")
	if !ok {
		return drawnCell{}, false
	}
	xTok, rest, ok := cutField(rest, ' ')
	if !ok {
		return drawnCell{}, false
	}
	yTok, rest, ok := cutField(rest, ' ')
	if !ok {
		return drawnCell{}, false
	}
	rest, ok = cutPrefix(rest, "Tm ")
	if !ok {
		return drawnCell{}, false
	}
	text, rest, ok := readPDFLiteral(rest)
	if !ok {
		return drawnCell{}, false
	}
	if _, ok = cutPrefix(rest, " Tj ET"); !ok {
		return drawnCell{}, false
	}
	size, err1 := strconv.ParseFloat(sizeTok, 64)
	x, err2 := strconv.ParseFloat(xTok, 64)
	y, err3 := strconv.ParseFloat(yTok, 64)
	if err1 != nil || err2 != nil || err3 != nil {
		return drawnCell{}, false
	}
	return drawnCell{font: font, size: size, x: x, y: y, text: text}, true
}

// cutPrefix is strings.CutPrefix, spelled out so the ok result reads the same way
// as the other two cutters here.
func cutPrefix(s, prefix string) (string, bool) {
	if !strings.HasPrefix(s, prefix) {
		return s, false
	}
	return s[len(prefix):], true
}

// cutField splits off everything up to the next sep.
func cutField(s string, sep byte) (field, rest string, ok bool) {
	i := strings.IndexByte(s, sep)
	if i < 0 {
		return "", s, false
	}
	return s[:i], s[i+1:], true
}

// readPDFLiteral decodes the string literal at the front of s, undoing the
// escaping printing.Page.literal applies. Only the escapes that writer emits are
// handled; anything else means this is not one of our text operators.
func readPDFLiteral(s string) (text, rest string, ok bool) {
	if len(s) == 0 || s[0] != '(' {
		return "", s, false
	}
	var sb strings.Builder
	depth := 0
	for i := 0; i < len(s); i++ {
		switch s[i] {
		case '(':
			if depth > 0 {
				sb.WriteByte('(')
			}
			depth++
		case ')':
			depth--
			if depth == 0 {
				return sb.String(), s[i+1:], true
			}
			sb.WriteByte(')')
		case '\\':
			if i+1 >= len(s) {
				return "", s, false
			}
			i++
			switch s[i] {
			case 'n':
				sb.WriteByte('\n')
			case 'r':
				sb.WriteByte('\r')
			case 't':
				sb.WriteByte('\t')
			case '(', ')', '\\':
				sb.WriteByte(s[i])
			default:
				return "", s, false
			}
		default:
			sb.WriteByte(s[i])
		}
	}
	return "", s, false
}

// pdfRowAtBaseline returns the printed row that the cell with text exactly label
// belongs to: the CONTIGUOUS run of cells around it that share its baseline.
// drawRow draws a row's cells one after another at one baseline, so contiguity
// plus a shared y is a row — and contiguity is what stops this collecting a row
// from ANOTHER PAGE, since every page reuses the same baselines.
func pdfRowAtBaseline(cells []drawnCell, label string) []drawnCell {
	at := -1
	for i, c := range cells {
		if c.text == label {
			at = i
			break
		}
	}
	if at < 0 {
		return nil
	}
	lo, hi := at, at
	for lo > 0 && cells[lo-1].y == cells[at].y {
		lo--
	}
	for hi+1 < len(cells) && cells[hi+1].y == cells[at].y {
		hi++
	}
	return cells[lo : hi+1]
}

// pdfCellWithText returns the cell in row whose text is exactly s.
func pdfCellWithText(row []drawnCell, s string) (drawnCell, bool) {
	for _, c := range row {
		if c.text == s {
			return c, true
		}
	}
	return drawnCell{}, false
}

// pdfSameColumn reports whether two cells share a right edge, i.e. sit in the
// same right-aligned column. The tolerance is a hundredth of a point: the writer
// emits coordinates to two decimals (printing.fmtNum), so cells genuinely in one
// column agree exactly and the slack is only against that rounding.
func pdfSameColumn(a, b float64) bool {
	d := a - b
	return d < 0.02 && d > -0.02
}

// indexRun finds want as a CONTIGUOUS run in lines at or after `from`, returning
// the index of its first element or -1. Contiguity is the whole point: it pins
// the ORDER of the cells within the row, which a column swap defeats and a
// "does the document contain this string anywhere" check does not.
func indexRun(lines, want []string, from int) int {
	if len(want) == 0 || from < 0 {
		return -1
	}
	for i := from; i+len(want) <= len(lines); i++ {
		match := true
		for k, w := range want {
			if lines[i+k] != w {
				match = false
				break
			}
		}
		if match {
			return i
		}
	}
	return -1
}

// countExact returns how many elements of lines are exactly s.
func countExact(lines []string, s string) int {
	n := 0
	for _, l := range lines {
		if l == s {
			n++
		}
	}
	return n
}

// tbPrintedRow is one expected printed body row of a Trial Balance: the ledger
// name it belongs to (for the message) and the run of cells the renderer must
// draw for it, in column order.
type tbPrintedRow struct {
	ledger string
	cells  []string
}

// trialBalanceRowRuns turns the JSON Trial Balance's rows into the runs the
// printed copy must contain, in the same order.
//
// The four columns are Particulars, Group, Debit, Credit (see printTrialBalance).
// A zero figure is BLANK on paper — printMoneyOrBlank, because "0.00" in the
// credit column asserts a credit balance of zero rather than "this ledger is not
// on that side" — and a blank cell draws nothing, so it contributes no element to
// the run. That is reproduced here rather than assumed: the run is exactly what
// the renderer must emit.
func trialBalanceRowRuns(t *testing.T, jbody map[string]any) []tbPrintedRow {
	t.Helper()
	raw, _ := jbody["rows"].([]any)
	if len(raw) == 0 {
		t.Fatalf("the JSON Trial Balance reported NO ledger rows, so a row-for-row comparison " +
			"with the printed copy would pass without comparing anything")
	}
	out := make([]tbPrintedRow, 0, len(raw))
	for i, r := range raw {
		m, ok := r.(map[string]any)
		if !ok {
			t.Fatalf("JSON Trial Balance row %d is not an object: %v", i, r)
		}
		ledger, _ := m["ledger"].(string)
		group, _ := m["group"].(string)
		debit, _ := m["debit"].(string)
		credit, _ := m["credit"].(string)
		if ledger == "" || debit == "" || credit == "" {
			t.Fatalf("JSON Trial Balance row %d is missing a field (%v)", i, m)
		}
		cells := []string{ledger, group,
			moneyOrBlankFromJSON(t, debit), moneyOrBlankFromJSON(t, credit)}
		run := make([]string, 0, len(cells))
		for _, c := range cells {
			if c != "" {
				run = append(run, c)
			}
		}
		out = append(out, tbPrintedRow{ledger: ledger, cells: run})
	}
	return out
}

// moneyOrBlankFromJSON renders a JSON figure the way the printed copy must:
// FormatMoney of the decimal the books hold, and BLANK for an exact zero. Parsed
// with decimal.NewFromString — never a float.
func moneyOrBlankFromJSON(t *testing.T, s string) string {
	t.Helper()
	d, err := decimal.NewFromString(s)
	if err != nil {
		t.Fatalf("the JSON Trial Balance reported %q, which is not a decimal", s)
	}
	if d.IsZero() {
		return ""
	}
	return printing.FormatMoney(d)
}

