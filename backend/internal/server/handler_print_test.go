// TestAnOperatorCouldReadThePayrollVoucherThroughTheSalesPrintRoute is the
// security gate of this whole slice.
//
// The PDP decides from the class in the PATH, before a row is read, because that
// is what makes `allow print sales` / `disallow print payroll` writable at all.
// The id is therefore UNCHECKED at decision time. Unless the handler compares the
// path class against the STORED class, a level holding `allow print sales` — which
// migration 0038 grants to every seeded Data Entry level in every tenant — can ask
// for /print/vouchers/sales/<a payroll voucher's id> and be handed the company's
// wage bill.
//
// The refusal is a 404 whose body is IDENTICAL to the one a non-existent id gets.
// A 403 would confirm that a voucher with that id exists here, and somebody who
// can enumerate ids could then count the pay runs.
func TestAnOperatorCouldReadThePayrollVoucherThroughTheSalesPrintRoute(t *testing.T) {
	s := payrollServer(t)
	f := newPrintFixture(t, s)

	// CONTROL A: the pay run IS reachable through its OWN class route, so the 404
	// below is attributable to the class check and not to the voucher being
	// invisible, deleted, or in another tenant. printingdb prints no document for
	// a Payroll voucher (a pay run's document is a payslip, per employee), so the
	// honest answer through its own route is a 400 that NAMES the class.
	rec := printGet(t, s, f.base+"/print/vouchers/payroll/"+f.payrollID, f.ownerTok)
	if rec.Code != http.StatusBadRequest {
		t.Fatalf("CONTROL: printing the pay run through /print/vouchers/payroll = %d, want 400 "+
			"(no printable document for that class). Without this control the 404 below proves "+
			"nothing about the class check (%s)", rec.Code, rec.Body.String())
	}
	if !strings.Contains(rec.Body.String(), "Payroll") {
		t.Errorf("the refusal for a pay run does not name the class: %s — an operator gets a bare "+
			"400 and goes looking for a missing ACL rule", rec.Body.String())
	}

	// THE GATE. Same voucher, asked for through the SALES print route.
	rec = printGet(t, s, f.base+"/print/vouchers/sales/"+f.payrollID, f.ownerTok)
	if rec.Code != http.StatusNotFound {
		t.Fatalf("printing PAY RUN voucher %s through /print/vouchers/sales/ returned %d, want 404: "+
			"the ACL decision is taken from the class in the PATH, so any level holding "+
			"`allow print sales` (migration 0038 grants it to every seeded Data Entry level) can "+
			"read the company's WAGE BILL through the sales print route. Body: %s",
			f.payrollID, rec.Code, rec.Body.String())
	}

	// And a SALES voucher asked for through the RECEIPT route, i.e. the same hole
	// in the other direction — a level granted print on one class must not reach
	// another class's document with it.
	rec = printGet(t, s, f.base+"/print/vouchers/receipt/"+f.salesID, f.ownerTok)
	if rec.Code != http.StatusNotFound {
		t.Fatalf("printing SALES voucher %s through /print/vouchers/receipt/ returned %d, want 404: "+
			"a level allowed `print receipt` and refused `print sales` would be handed the invoice "+
			"its level was explicitly refused. Body: %s", f.salesID, rec.Code, rec.Body.String())
	}

	// CONTROL B: the refusal must not CONFIRM that the voucher exists. The body
	// for a class mismatch must be byte-identical to the body for an id that is
	// not in this company at all.
	mismatch := printGet(t, s, f.base+"/print/vouchers/sales/"+f.payrollID, f.ownerTok).Body.String()
	absent := printGet(t, s, f.base+"/print/vouchers/sales/"+uuid.NewString(), f.ownerTok)
	if absent.Code != http.StatusNotFound {
		t.Fatalf("printing a voucher id that does not exist = %d, want 404 (%s)", absent.Code, absent.Body.String())
	}
	if mismatch != absent.Body.String() {
		t.Errorf("the class-mismatch refusal (%s) differs from the not-found refusal (%s): the "+
			"difference tells a caller that a voucher with that id EXISTS in this company, which "+
			"is exactly the fact the refusal is protecting", strings.TrimSpace(mismatch),
			strings.TrimSpace(absent.Body.String()))
	}
}

