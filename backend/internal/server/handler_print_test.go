// seededDataEntryRules is the seeded 'Data Entry' level as an owner sees it in
// Users & Roles: its id, every rule it holds (in the shape the PUT wants back),
// and its `print` rules split by effect.
type seededDataEntryRules struct {
	levelID       string
	rules         []map[string]string
	allowPrint    map[string]bool
	disallowPrint map[string]bool
}

// readSeededDataEntryRules reads them through the admin API rather than out of the
// database, because the admin API is where an owner would look and is the surface
// a lost seed row has to be visible on.
func readSeededDataEntryRules(t *testing.T, s *Server, f printFixture) seededDataEntryRules {
	t.Helper()
	out := seededDataEntryRules{
		allowPrint:    map[string]bool{},
		disallowPrint: map[string]bool{},
	}
	rec, body := aclRequest(t, s, http.MethodGet, f.base+"/security-levels", f.ownerTok, nil)
	if rec.Code != http.StatusOK {
		t.Fatalf("GET /security-levels = %d, want 200 (%s)", rec.Code, rec.Body.String())
	}
	levels, _ := body["security_levels"].([]any)
	for _, lv := range levels {
		m, _ := lv.(map[string]any)
		if name, _ := m["name"].(string); name != "Data Entry" {
			continue
		}
		out.levelID, _ = m["id"].(string)
		raw, _ := m["rules"].([]any)
		for _, r := range raw {
			rm, _ := r.(map[string]any)
			effect, _ := rm["effect"].(string)
			action, _ := rm["action"].(string)
			resource, _ := rm["resource"].(string)
			out.rules = append(out.rules, map[string]string{
				"effect": effect, "action": action, "resource": resource,
			})
			if action != "print" {
				continue
			}
			switch effect {
			case "allow":
				out.allowPrint[resource] = true
			case "disallow":
				out.disallowPrint[resource] = true
			}
		}
	}
	if out.levelID == "" {
		t.Fatalf("the company has no seeded 'Data Entry' security level (%s)", rec.Body.String())
	}
	return out
}

