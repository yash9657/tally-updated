// payrollServer) already exist in auth_payroll_itc_acl_test.go and
// handler_payroll_test.go and are reused rather than re-written.
//
// WHAT IS ASSERTED, AND WHAT IS DELIBERATELY NOT. The oracle for a rendered
// document is the TEXT EXTRACTED FROM THE GENERATED BYTES (printing.ExtractText
// over the uncompressed streams), never a screenshot and never "the handler
// returned 200 and some bytes". Where a figure is asserted, it is asserted as
// printing.FormatMoney of the amount that was POSTED, so a handler that printed a
// plausible-but-different number fails.
//
