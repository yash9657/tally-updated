// TestTheVoucherClassPathVocabularyIsExactlyTheACLVocabulary closes the gap
// between the two lists that decide which print requests are authorizable.
//
// routeAction derives the print resource token from the PATH and validates the
// segment with isVoucherClass, while an administrator's rule is validated against
// authz.KnownVoucherClasses. If the two ever disagree, one of two silent bugs
// follows and neither surfaces as an error:
//
//	a class in isVoucherClass but not in the vocabulary -> the router emits a
//	  resource token the admin API would REJECT in a rule, so only default_access
//	  can reach that route: an owner can neither delegate it nor take it back.
//	a class in the vocabulary but not in isVoucherClass -> an administrator can
//	  write `disallow print <class>` and it can never match, because no path
//	  produces that token. For a disallow, that is the system permitting exactly
//	  what somebody believes they forbade.
func TestTheVoucherClassPathVocabularyIsExactlyTheACLVocabulary(t *testing.T) {
	inVocabulary := map[string]bool{}
	for _, c := range authz.KnownVoucherClasses {
		inVocabulary[string(c)] = true
		if !isVoucherClass(string(c)) {
			t.Errorf("authz.KnownVoucherClasses names %q but isVoucherClass rejects it: an "+
				"administrator can write `disallow print %s` and no route will ever emit that "+
				"token, so the rule silently never matches", c, c)
		}
	}
	// The other direction, over the segments the print routes are actually
	// mounted on (routes() mounts one per vocabulary entry, so this also proves
	// the mount list and the validator agree).
	for _, seg := range []string{
		"sales", "purchase", "receipt", "payment", "contra", "journal",
		"credit-note", "debit-note", "delivery-note", "receipt-note",
		"stock-journal", "physical-stock", "payroll",
	} {
		if !isVoucherClass(seg) {
			t.Errorf("isVoucherClass rejects %q, which this test expects to be a class: the "+
				"list in this test is stale or a class was dropped", seg)
		}
		if !inVocabulary[seg] {
			t.Errorf("isVoucherClass accepts %q but authz.KnownVoucherClasses does not name it: "+
				"the router would emit a resource token the admin API rejects, so no ACL rule "+
				"could ever govern that route", seg)
		}
	}
}

// printRouteActionFor asks routeAction about a synthesized print path.
func printRouteActionFor(t *testing.T, path string) (authz.Action, authz.Resource, string, bool) {
	t.Helper()
	companyID := uuid.NewString()
	rctx := chi.NewRouteContext()
	rctx.URLParams.Add("companyID", companyID)
	req := httptest.NewRequest(http.MethodGet, "/v1/companies/"+companyID+path, nil).
		WithContext(context.WithValue(context.Background(), chi.RouteCtxKey, rctx))
	return routeAction(req)
}

// TestPrintIsItsOwnActionAndAnUnknownSegmentIsRefused pins the PDP mapping.
//
// The `print` action being distinct from `display` is the whole basis of
// migration 0038: 0011's coarse `allow display report` is action=display and must
// NOT reach a print request. If routeAction ever emitted Display for a print
// path, every seeded Data Entry level in every tenant would silently acquire a
// PDF of the payroll register, the priced supplier reconciliation and the cost
// book — by inheritance, without anybody deciding to.
func TestPrintIsItsOwnActionAndAnUnknownSegmentIsRefused(t *testing.T) {
	voucherID := uuid.NewString()

	act, res, name, mapped := printRouteActionFor(t, "/print/vouchers/sales/"+voucherID)
	if !mapped || act != authz.Print || res != "sales" || name != "" {
		t.Errorf("print a sales voucher mapped to (%q,%q,%q,%v), want (print,sales,\"\",true) — "+
			"if the action is display, migration 0011's coarse `allow display report` and every "+
			"`allow display sales` grant silently become print grants", act, res, name, mapped)
	}
	act, res, name, mapped = printRouteActionFor(t, "/print/reports/trial-balance")
	if !mapped || act != authz.Print || res != "report" || name != "trial-balance" {
		t.Errorf("print the Trial Balance mapped to (%q,%q,%q,%v), want (print,report,trial-balance,true)",
			act, res, name, mapped)
	}

	// An unknown class or report name must be UNMAPPED, which default-DENIES. A
	// typo'd segment that resolved to some other token could land on a token an
	// administrator's rule happens to allow.
	for _, path := range []string{
		"/print/vouchers/sale/" + voucherID,     // typo of "sales"
		"/print/vouchers/employee/" + voucherID, // a real resource, not a class
		"/print/reports/trial_balance",          // wrong separator
		"/print/reports/wage-bill",              // not a report at all
		"/print/vouchers/sales",                 // no voucher id
		"/print/vouchers/sales/" + voucherID + "/extra",
		"/print/reports",
		"/print",
	} {
		if _, _, _, mapped := printRouteActionFor(t, path); mapped {
			t.Errorf("routeAction MAPPED %q; an unrecognised print path must be unmapped so the "+
				"default-deny applies, or a typo becomes an authorization decision nobody wrote", path)
		}
	}

	// And print must never be treated as a write: a write inherits the back-dated
	// cutoff and the WebAuthn step-up, and asking for a second factor to reprint
	// an invoice moves the printing to a spreadsheet.
	if authz.Print.IsWrite() {
		t.Fatal("authz.Print.IsWrite() is true: the print routes would inherit the back-dated " +
			"write cutoff and the Owner level's WebAuthn step-up, so an operator could not " +
			"reprint the invoice they just keyed without a second factor")
	}
}

// TestAVoucherNumberCannotInjectAResponseHeader pins pdfFilename's sanitisation.
//
// A voucher number is USER TEXT and Tally series routinely contain '/'
// ("INV/2026/0041"). The filename goes into a Content-Disposition header value,
// so a carriage return in it would end the header and let a voucher number write
// response headers of its own.
func TestAVoucherNumberCannotInjectAResponseHeader(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"INV/2026/0041", "INV-2026-0041.pdf"},
		{"RCPT 12", "RCPT-12.pdf"},
		{"a\r\nSet-Cookie: x=y", "a-Set-Cookie-x-y.pdf"},
		{`he"llo`, "he-llo.pdf"},
		{"", "document.pdf"},
		{"///", "document.pdf"},
	} {
		if got := pdfFilename(tc.in); got != tc.want {
			t.Errorf("pdfFilename(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
	// The composed form, and the guarantee that matters: nothing that could
	// terminate a header value survives.
	got := pdfFilename("sales", "INV/1\r\n", uuid.NewString())
	if strings.ContainsAny(got, "\r\n\"") {
		t.Fatalf("pdfFilename produced %q, which contains a CR, LF or quote: a voucher number "+
			"would be able to inject a response header", got)
	}
}

