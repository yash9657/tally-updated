package printing

import (
	"bytes"
	"errors"
	"fmt"
	"strconv"
)

// ErrNoPages is returned by Bytes when nothing was drawn. A PDF whose /Pages
// tree has /Count 0 is rejected outright by some readers and shown as a blank
// grey window by others, so we refuse to produce one rather than hand a user a
// file that "does not open".
var ErrNoPages = errors.New("printing: a document with no pages cannot be printed")

// Doc is a PDF document under construction: a page size, the pages, and any
// offence recorded while text was added.
//
// DETERMINISM IS A HARD REQUIREMENT OF THIS TYPE.
// Bytes() on the same sequence of calls returns byte-identical output, in this
// process and in any other, today and next year. That is what makes a golden
// test on the generated bytes meaningful — the alternative is asserting on a
// screenshot, which cannot tell a wrong total from a right one. Concretely:
//
//   - NO /CreationDate and NO /ModDate. The clock never enters the output. A
//     timestamp would change every byte after it and defeat every golden test,
//     and the date that matters (the voucher date) is drawn on the page anyway.
//   - NO /ID in the trailer. /ID is optional for an unencrypted file and every
//     recipe for generating one is a hash of the current time.
//   - NO random or uuid object names. Font resource names are fixed per Font
//     value (F1..F5) and object numbers are assigned by position.
//   - NO map iteration in emission order. Every list written out is a slice.
//   - NO compression. Streams are plain text, so the bytes are diffable and a
//     reviewer can grep an invoice for the total that is supposed to be on it.
//     A FlateDecode stream would also make the output depend on the compressor's
//     version.
type Doc struct {
	size  PageSize
	pages []*Page
	errs  []error
}

// NewDoc starts a document whose pages are all the given size.
func NewDoc(size PageSize) *Doc {
	return &Doc{size: size}
}

// NewPage appends a page and returns it. The returned Page draws in PDF user
// space: origin bottom-left, y increasing upward (see the Page doc comment).
func (d *Doc) NewPage() *Page {
	p := &Page{doc: d, size: d.size}
	d.pages = append(d.pages, p)
	return p
}

// PageCount reports how many pages have been added.
func (d *Doc) PageCount() int { return len(d.pages) }

// note records a deferred failure — today, only an unencodable rune. It is
// deliberately not returned from the drawing calls: a renderer laying out a
// 40-line invoice would either ignore 40 error returns or become unreadable, so
// the offence is carried to Bytes() where a caller cannot ignore it.
func (d *Doc) note(err error) {
	if err != nil {
		d.errs = append(d.errs, err)
	}
}

// Err reports the first offence recorded while the document was built, without
// serialising it.
func (d *Doc) Err() error {
	if len(d.errs) > 0 {
		return d.errs[0]
	}
	return nil
}

// Object numbers 1..7 are fixed, which is what lets every page reference the
// same /Pages parent and the same /Resources without a lookup table.
const (
	objCatalog   = 1
	objPages     = 2
	objFirstFont = 3 // objFirstFont .. objFirstFont+len(allFonts)-1
)

// Bytes serialises the document. It does not mutate the Doc, so it may be called
// twice and both calls return identical bytes.
func (d *Doc) Bytes() ([]byte, error) {
	if err := d.Err(); err != nil {
		return nil, err
	}
	if len(d.pages) == 0 {
		return nil, ErrNoPages
	}

	objResources := objFirstFont + len(allFonts)
	objInfo := objResources + 1
	firstPageObj := objInfo + 1
	// Each page costs two objects: the page dictionary and its content stream.
	pageObj := func(i int) int { return firstPageObj + 2*i }
	contentObj := func(i int) int { return firstPageObj + 2*i + 1 }
	objCount := firstPageObj + 2*len(d.pages) - 1

	// bodies[n] is object n's body, indexed by object number; index 0 is unused
	// so that the slice index IS the object number.
	bodies := make([][]byte, objCount+1)

	bodies[objCatalog] = []byte("<< /Type /Catalog /Pages " + ref(objPages) + " >>")

	var kids bytes.Buffer
	kids.WriteByte('[')
	for i := range d.pages {
		if i > 0 {
			kids.WriteByte(' ')
		}
		kids.WriteString(ref(pageObj(i)))
	}
	kids.WriteByte(']')
	bodies[objPages] = []byte("<< /Type /Pages /Count " + strconv.Itoa(len(d.pages)) +
		" /Kids " + kids.String() + " >>")

	var fontRes bytes.Buffer
	for i, f := range allFonts {
		n := objFirstFont + i
		bodies[n] = []byte("<< /Type /Font /Subtype /Type1 /BaseFont /" +
			f.baseFontName() + " /Encoding /WinAnsiEncoding >>")
		if i > 0 {
			fontRes.WriteByte(' ')
		}
		fontRes.WriteString("/" + f.resourceName() + " " + ref(n))
	}
	bodies[objResources] = []byte("<< /Font << " + fontRes.String() +
		" >> /ProcSet [/PDF /Text] >>")

	// The Info dictionary carries a FIXED producer string and no dates at all.
	bodies[objInfo] = []byte("<< /Producer (cored printing: hand-rolled PDF 1.4 writer, base-14 fonts) >>")

	for i, p := range d.pages {
		mb := "[0 0 " + fmtNum(p.size.Width) + " " + fmtNum(p.size.Height) + "]"
		bodies[pageObj(i)] = []byte("<< /Type /Page /Parent " + ref(objPages) +
			" /MediaBox " + mb + " /Resources " + ref(objResources) +
			" /Contents " + ref(contentObj(i)) + " >>")

		content := p.content()
		var stream bytes.Buffer
		stream.WriteString("<< /Length " + strconv.Itoa(len(content)) + " >>\nstream\n")
		stream.Write(content)
		stream.WriteString("\nendstream")
		bodies[contentObj(i)] = stream.Bytes()
	}

	var out bytes.Buffer
	out.WriteString("%PDF-1.4\n")
	// A comment line with four bytes above 127, as the spec recommends, so that a
	// transfer agent classifies the file as binary and does not "fix" line
	// endings — which would break every xref offset below.
	out.WriteString("%\xE2\xE3\xCF\xD3\n")

	offsets := make([]int, objCount+1)
	for n := 1; n <= objCount; n++ {
		if bodies[n] == nil {
			return nil, fmt.Errorf("printing: internal error, object %d was never built", n)
		}
		offsets[n] = out.Len()
		out.WriteString(strconv.Itoa(n))
		out.WriteString(" 0 obj\n")
		out.Write(bodies[n])
		out.WriteString("\nendobj\n")
	}

	// The cross-reference table. Every entry is EXACTLY 20 bytes
	// ("%010d %05d n \n"); a 19- or 21-byte entry makes a file that some readers
	// open and others reject, which is the worst possible failure mode because it
	// passes local testing. The free-list head is object 0, generation 65535.
	xref := out.Len()
	out.WriteString("xref\n0 " + strconv.Itoa(objCount+1) + "\n")
	out.WriteString("0000000000 65535 f \n")
	for n := 1; n <= objCount; n++ {
		out.WriteString(fmt.Sprintf("%010d 00000 n \n", offsets[n]))
	}
	out.WriteString("trailer\n<< /Size " + strconv.Itoa(objCount+1) +
		" /Root " + ref(objCatalog) + " /Info " + ref(objInfo) + " >>\n")
	out.WriteString("startxref\n" + strconv.Itoa(xref) + "\n")
	out.WriteString("%%EOF")

	return out.Bytes(), nil
}

// ref renders an indirect reference to object n.
func ref(n int) string { return strconv.Itoa(n) + " 0 R" }
