// Package tau is the W1a state-based task harness: a tau-bench-shaped suite of
// bookkeeping tasks, each judged by THE LEDGER STATE AFTER THE RUN and never by
// the transcript, with pass^k over repeated trials.
//
// WHY STATE AND NOT TRANSCRIPT. An agent that says "posted a sales invoice to
// Acme for ₹59,000" and posted ₹5,900, or posted it to Acme Components instead
// of Acme Traders, has a perfect transcript. The only question a bookkeeper
// cares about is what the books say afterwards, so that is the only question
// this package asks: it snapshots the company's masters and vouchers into a
// canonical JSON form (state.go), and a task passes when that snapshot equals
// the task's EXPECTED state — every voucher and master, including the ones the
// task seeded, compared as a multiset. A write the task did not ask for is a
// failure exactly like a missing one.
//
// WHY pass^k AND NOT pass@k. pass@k rewards an agent that gets it right once in
// five tries; pass^k (tau-bench, Yao et al. 2024) is the probability that ALL k
// independent trials pass, which is the property a user who posts forty
// vouchers a day actually experiences. passk.go carries the unbiased estimator.
//
// WHAT THE HARNESS PROMISES AN AGENT UNDER TEST, AND WHAT IT WITHHOLDS. An
// Agent receives a Prompt (the utterance, its language, the task id) and a
// Books handle — an authenticated HTTP surface scoped to one freshly created,
// freshly seeded company. It never receives the Task: the expected state and
// the reference plan are in the Task, and an agent that could read them would
// be graded against its own answer key. The scripted ReferenceAgent is given
// its plans at CONSTRUCTION, from the same fixture file, which is the one place
// the two are allowed to meet — and it exists to prove the suite is solvable
// against the real engine, not to be scored.
//
// WHY THE HARNESS IS PROVEN AGAINST THREE AGENTS, NOT ONE. A judge that passes
// everything is indistinguishable from a working judge if the only agent ever
// run is the reference. So tau_db_test.go runs three: the reference (must pass
// every task), the NullAgent (must fail every task EXCEPT the guard tasks,
// whose correct answer is "do not write"), and the WrongAgent (must fail every
// task, including the guard tasks, where it executes the tempting write a naive
// agent would make). The three exact counts are pinned.
//
// ⛔ THE FIXTURES ARE SYNTHETIC AND SAY SO. corpora/tau/*.json is generated by
// corpora/tau/generate.py from hand-written templates; every file carries
// "synthetic": true and a provenance line naming the generator. The expected
// state is COMPUTED BY THE GENERATOR (Python decimal arithmetic, independently
// re-derived again by corpora/validate.py) and never recorded from a run of
// this engine: a recorded expectation would make the reference agent's pass
// circular. That the Go engine reproduces a Python-computed state to the paisa
// on every task is the claim the reference run makes.
//
// ⛔ NO NETWORK. Nothing in this package reaches a model provider. A
// model-backed agent (W1b's bake-off, W2's loop) implements Agent in its own
// package and reaches a model through internal/llm; this package only judges.
