// TestRegistryIsNotEmpty is the anti-vacuity guard every walker/census in this
// repo carries (archtest boundaries_test.go:746/:829/:877, testhygiene:528,
// route_vocabulary_test.go:120). Without it, a generator that silently produced
// nothing — a renamed prefix, a router that failed to build, a botched
// regeneration — would leave every assertion below trivially satisfied, and the
// suite would report a clean bill of health forever.
func TestRegistryIsNotEmpty(t *testing.T) {
	if len(Specs) == 0 {
		t.Fatal("Specs is EMPTY. Every assertion in this file is vacuous on an empty registry, " +
			"so this is the one failure that must be reported first.\n" +
			"Regenerate: UPDATE_GOLDENS=1 go test ./internal/server/ -run TestActionRegistryGolden")
	}
}

// TestRegistryCoversTheActionVocabulary is the W0 gate proper: ">= 60 actions",
// plus the floors and the shape checks that make that number mean something.
func TestRegistryCoversTheActionVocabulary(t *testing.T) {
	// The stated W0 gate (PLAN-AGENTIC §3 W0: "coverage test enumerates >= 60
	// actions").
	const w0Gate = 60
	// ⚠️ AND THE REAL FLOOR, WHICH IS MUCH HIGHER. 230 (method, route) pairs are
	// mounted under {companyID} today. A registry that satisfied the W0 gate with
	// 61 rows would be a registry that lost two thirds of the product between one
	// regeneration and the next — a truncated walk, a prefix typo, a router half
	// built — and 60 alone would call that a pass. The floor is set below 230 so
	// deleting a feature does not trip it, and far above 60 so losing the walk
	// does.
	const realFloor = 150

	if len(Specs) < w0Gate {
		t.Fatalf("registry has %d specs, below the stated W0 gate of %d", len(Specs), w0Gate)
	}
	if len(Specs) < realFloor {
		t.Fatalf("registry has %d specs, want >= %d. The router mounts ~230 company-scoped "+
			"(method, route) pairs; a count this low means the generator walked a subset, not "+
			"that the product shrank. Regenerate and read the diff before changing this floor",
			len(Specs), realFloor)
	}

	byAction := map[authz.Action]int{}
	var writes, reads int
	for _, s := range Specs {
		byAction[s.Action]++
		if s.IsWrite {
			writes++
		} else {
			reads++
		}
	}
	// Every verb in the closed vocabulary must be represented. A missing verb is
	// how a whole class of operation (every delete, say) silently leaves the
	// registry: the count barely moves and nothing else notices.
	for _, a := range authz.KnownActions {
		if byAction[a] == 0 {
			t.Errorf("no spec carries action %q, but it is in authz.KnownActions. Either the "+
				"router stopped mounting anything with that verb, or the generator stopped "+
				"seeing it", a)
		}
	}
	if writes == 0 {
		t.Error("no spec is a write. The agent layer's whole approval machinery hangs off " +
			"IsWrite; a registry with no writes would make every autonomy check trivially safe " +
			"and trivially wrong")
	}
	if reads == 0 {
		t.Error("no spec is a read. Every report in the vocabulary should be here")
	}

	t.Logf("%d specs: %s (%d writes, %d reads)", len(Specs), formatCounts(byAction), writes, reads)
}

// TestTheDerivationIsRight is THE CONTROL for the count above, and it is the
// reason that count is not the whole gate.
//
// A do-nothing generator that emitted 230 rows of zero values would satisfy
// every floor in this file. What it could not satisfy is a handful of rows
// whose exact ACL key is known independently — from the PDP's own vocabulary and
// from the comments on routeAction's arms — so those are pinned here by hand.
//
// ⛔ THESE FIVE ARE CHOSEN, NOT SAMPLED. Each one is a place where the obvious
// wrong derivation — deriving the ACL key from the screen name or the URL
// segment — gives a DIFFERENT answer:
//
//	get.tds-challans   the route says `tds-challans`, the key is the SINGULAR
//	                   bare token `tds-challan`. A screen-name derivation is
//	                   wrong here and the failure is invisible: `display
//	                   tds-challans` validates as... nothing, and no rule matches.
//	get.day-book       a `report:NAME` frame, so the resource splits in two.
//	get.print.reports.balance-sheet
//	                   `print` is NOT a write and takes no step-up. Anything that
//	                   treated "the print routes" as exports or as writes lands
//	                   here.
//	post.vouchers.sales / put.vouchers.sales._voucherid
//	                   the write pair: same resource, different verb. A
//	                   generator that mapped method->action by a
//	                   table (POST=create, PUT=alter) would pass these two and
//	                   fail the bank-reconciliation DELETE below, which is `alter`
//	                   and not `delete`.
//	delete.bank-reconciliation._ledgerid._voucherid._legno
//	                   a DELETE whose arm is `alter`, and whose cutoff refusal
//	                   names the BANK DATE rather than a voucher date.
func TestTheDerivationIsRight(t *testing.T) {
	want := []ActionSpec{
		{ID: "get.tds-challans", ACLKey: "display tds-challan", IsWrite: false, StepUpEligible: false},
		{ID: "get.day-book", ACLKey: "display report:day-book", IsWrite: false, StepUpEligible: false},
		{ID: "get.print.reports.balance-sheet", ACLKey: "print report:balance-sheet", IsWrite: false, StepUpEligible: false},
		{ID: "post.vouchers.sales", ACLKey: "create sales", IsWrite: true, StepUpEligible: true},
		{ID: "put.vouchers.sales._voucherid", ACLKey: "alter sales", IsWrite: true, StepUpEligible: true},
		{
			ID: "delete.bank-reconciliation._ledgerid._voucherid._legno", ACLKey: "alter bank-reconciliation",
			IsWrite: true, StepUpEligible: true, DateSubject: "bank date",
		},
	}
	for _, w := range want {
		got, ok := ByID(w.ID)
		if !ok {
			t.Errorf("no spec with id %q. Either the route moved (regenerate and update this "+
				"control in the same commit) or the generator stopped producing it", w.ID)
			continue
		}
		if got.ACLKey != w.ACLKey {
			t.Errorf("%s: ACLKey = %q, want %q. The ACL key IS the arm; a mismatch here means "+
				"the registry and the PDP disagree about who may drive this route",
				w.ID, got.ACLKey, w.ACLKey)
		}
		if got.IsWrite != w.IsWrite {
			t.Errorf("%s: IsWrite = %t, want %t", w.ID, got.IsWrite, w.IsWrite)
		}
		if got.StepUpEligible != w.StepUpEligible {
			t.Errorf("%s: StepUpEligible = %t, want %t", w.ID, got.StepUpEligible, w.StepUpEligible)
		}
		if got.DateSubject != w.DateSubject {
			t.Errorf("%s: DateSubject = %q, want %q", w.ID, got.DateSubject, w.DateSubject)
		}
	}
}

// TestPrintIsNotAWrite pins the one fact about the vocabulary that an autonomy
// table is most likely to get wrong in the "safe" direction.
//
// authz.Action.IsWrite() is create|alter|delete ONLY. Printing takes neither the
// back-dated cutoff nor the WebAuthn step-up, and a policy layer that treated it
// as a write would be STRICTER THAN THE PRODUCT — which sounds harmless and is
// not: it would diverge from what the tenant's own ACL rules do, so an owner who
// granted `allow print report:balance-sheet` would watch the agent refuse.
func TestPrintIsNotAWrite(t *testing.T) {
	prints := 0
	for _, s := range Specs {
		if s.Action != authz.Print {
			continue
		}
		prints++
		if s.IsWrite {
			t.Errorf("%s carries action print and IsWrite=true; authz.Action.IsWrite is "+
				"create|alter|delete only", s.ID)
		}
		if s.StepUpEligible {
			t.Errorf("%s carries action print and is marked step-up eligible; webauthnDeny "+
				"runs on create|alter|delete only, so a WebAuthn prompt can never stand "+
				"between an operator and a printout", s.ID)
		}
	}
	if prints == 0 {
		t.Fatal("no print specs at all, so this test asserted nothing. The router mounts a " +
			"print route per report name and per voucher class")
	}
}

// TestOnlyWritesAreStepUpEligible pins the shape of the WebAuthn step-up's
// reach, and RECORDS the fact that the column is redundant today.
//
// ⚠️ StepUpEligible AND IsWrite COINCIDE ON EVERY ROW, AND THIS TEST SAYS SO OUT
// LOUD RATHER THAN LEAVING IT TO BE REDISCOVERED. webauthnDeny has exactly one
// trigger — the action is a write — so the generator's authz.Evaluate call
// currently yields nothing `act.IsWrite()` would not. It is still a call to the
// PDP and not a re-statement of its rule, which is what makes the column start
// disagreeing by itself the day step-up grows a second trigger; see
// ActionSpec.StepUpEligible for why that is worth a column and why the
// back-dated cutoff's equivalent was deleted instead of documented.
//
// ⛔ THE COINCIDENCE IS LOGGED, NOT ASSERTED, AND THE DIRECTION IS. Asserting
// the identity would make the arrival of a second trigger a red build in the
// package that merely OBSERVES the PDP. What must never stop being true is the
// direction: no READ is step-up eligible. A read marked eligible would mean the
// registry believes a WebAuthn prompt can stand between an operator and a
// report, and an agent built on it would tell them to touch a key that the
// product never asks for.
func TestOnlyWritesAreStepUpEligible(t *testing.T) {
	eligible, coincide := 0, 0
	for _, s := range Specs {
		if s.StepUpEligible {
			eligible++
			if !s.IsWrite {
				t.Errorf("%s (%s %s -> %q) is a READ marked step-up eligible. webauthnDeny only "+
					"ever runs on create|alter|delete", s.ID, s.Method, s.Route, s.ACLKey)
			}
		}
		if s.StepUpEligible == s.IsWrite {
			coincide++
		}
	}
	if eligible == 0 {
		t.Fatal("not one spec is step-up eligible, so this test asserted nothing. Every write " +
			"in the product can be refused with STEPUP_REQUIRED at a level that requires " +
			"WebAuthn; a zero here means the generator stopped calling authz.Evaluate")
	}
	t.Logf("%d of %d specs step-up eligible; StepUpEligible == IsWrite on %d of %d rows "+
		"(one trigger, so the column is redundant until there are two)",
		eligible, len(Specs), coincide, len(Specs))
}

// TestOnlyWritesNameADateSubject is what remains of the back-dated cutoff's own
// coverage here, and it is the part that was ever measurable per route.
//
// DateSubject comes from cutoffDateSubject, which reads the METHOD AND THE PATH
// and nothing else — so unlike the deleted CutoffJudged column it describes the
// request the product actually sends. Non-empty means a cutoff refusal on this
// route would name something an operator would not call a voucher date, and
// getting that wrong sends them to look at the wrong field on the wrong screen.
func TestOnlyWritesNameADateSubject(t *testing.T) {
	named := map[string]int{}
	for _, s := range Specs {
		if s.DateSubject == "" {
			continue
		}
		named[s.DateSubject]++
		if !s.IsWrite {
			t.Errorf("%s (%s %s) is a READ naming date subject %q. The back-dated cutoff only "+
				"runs on create|alter|delete, so no read has a cutoff refusal to name",
				s.ID, s.Method, s.Route, s.DateSubject)
		}
	}
	// The two subjects cutoffDateSubject can return. A zero here means the
	// derivation stopped calling it and every refusal reverted to naming the
	// voucher date — on the two route families where that names nothing the
	// operator touched.
	for _, want := range []string{"bank date", "deposit date"} {
		if named[want] == 0 {
			t.Errorf("no spec names date subject %q. cutoffDateSubject returns it for the "+
				"bank-reconciliation legs and the allocate-later challan route respectively; "+
				"zero means the generator is no longer asking it", want)
		}
	}
	t.Logf("date subjects across %d specs: %v", len(Specs), named)
}

