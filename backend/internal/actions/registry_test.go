// TestEveryACLKeyCanBeWrittenAsARule is the assertion the whole registry exists
// to make checkable: for every action the agent layer could be handed, an
// administrator can WRITE A RULE that names it.
//
// ⛔ THIS IS THE `export` DEFECT'S CONVERSE. That token failed because it was
// writable and governed nothing. The failure available HERE is the mirror image:
// a route the agent can drive whose key no rule can name, so the only thing that
// could ever reach it is default_access. Both are "a control that is not where
// the operator thinks it is"; this test closes the second one.
func TestEveryACLKeyCanBeWrittenAsARule(t *testing.T) {
	checked := 0
	for _, s := range Specs {
		checked++
		rule := authz.Rule{Effect: authz.Allow, Action: s.Action, Resource: s.RuleResource()}
		if err := authz.ValidateRule(rule); err != nil {
			t.Errorf("%s (%s %s) has ACL key %q, which authz.ValidateRule REJECTS: %v\n"+
				"No administrator could write a rule naming this action, so nothing but "+
				"default_access can govern it", s.ID, s.Method, s.Route, s.ACLKey, err)
		}
		// The key an operator types and the tuple the PDP compares must be the
		// same string, produced once. A spec whose ACLKey does not round-trip is a
		// row where the two spellings have already diverged.
		if got := RenderACLKey(s.Action, s.Resource, s.ResourceName); got != s.ACLKey {
			t.Errorf("%s: ACLKey %q does not round-trip through RenderACLKey (%q)", s.ID, s.ACLKey, got)
		}
	}
	if checked == 0 {
		t.Fatal("checked no specs")
	}
}

// TestValidateRuleActuallyRejectsADeadToken IS THE CONTROL FOR THE TEST ABOVE,
// and without it that test is worth nothing.
//
// A ValidateRule that returned nil unconditionally — because somebody loosened
// the vocabulary, or because a future refactor made ValidResource fall through —
// would satisfy every row in TestEveryACLKeyCanBeWrittenAsARule while proving
// exactly nothing. The insightd precedent states it plainly
// (tests/test_pii_persistence.py:183): "THE CONTROL. A path that redacts
// everything looks identical to a working one."
//
// The malformed key is `export report:day-book`, and the token is not chosen at
// random: `export` was DELETED from authz.KnownActions after it shipped as a
// setting that validated, was shown to the owner as saved, and governed nothing
// (vocabulary.go:24). internal/authz/vocabulary_export_test.go:22 is the
// precedent this mirrors. If this test ever goes green-by-passing — i.e. if
// ValidateRule starts accepting `export` again — the registry has quietly
// re-acquired the ability to describe an action nobody can enforce.
func TestValidateRuleActuallyRejectsADeadToken(t *testing.T) {
	malformed := ActionSpec{
		ID:           "control.export.report.day-book",
		Method:       "GET",
		Route:        "/v1/companies/{companyID}/day-book",
		Action:       authz.Action("export"),
		Resource:     authz.Resource("report"),
		ResourceName: "day-book",
	}
	malformed.ACLKey = RenderACLKey(malformed.Action, malformed.Resource, malformed.ResourceName)
	if malformed.ACLKey != "export report:day-book" {
		t.Fatalf("the control's own key rendered as %q; RenderACLKey changed shape and this "+
			"control no longer says what it claims", malformed.ACLKey)
	}

	err := authz.ValidateRule(authz.Rule{
		Effect: authz.Allow, Action: malformed.Action, Resource: malformed.RuleResource(),
	})
	if err == nil {
		t.Fatal("authz.ValidateRule ACCEPTED `export report:day-book`.\n\n" +
			"Two things are wrong at once. `export` was deleted from the PDP vocabulary " +
			"precisely because it validated and enforced nothing (see " +
			"internal/authz/vocabulary.go:24 and vocabulary_export_test.go), so its return is " +
			"a live security regression. AND every ValidateRule assertion in " +
			"TestEveryACLKeyCanBeWrittenAsARule is now vacuous: a validator that accepts a " +
			"deleted token accepts anything, so it proves nothing about the 230 real rows.")
	}
	if !strings.Contains(err.Error(), "export") {
		t.Errorf("ValidateRule rejected the control but its message does not name the offending "+
			"token (%q). The admin API surfaces this verbatim as a 422; an operator must be "+
			"able to see WHICH token was rejected", err)
	}

	// The other half of the control: a WELL-FORMED key built the same way must be
	// ACCEPTED. Without this, a ValidateRule that rejected everything would also
	// pass the check above — the same vacuity, mirrored.
	wellFormed := ActionSpec{Action: authz.Display, Resource: authz.Resource("report"), ResourceName: "day-book"}
	if err := authz.ValidateRule(authz.Rule{
		Effect: authz.Allow, Action: wellFormed.Action, Resource: wellFormed.RuleResource(),
	}); err != nil {
		t.Fatalf("authz.ValidateRule REJECTED the well-formed control key %q: %v. A validator "+
			"that refuses everything would make the malformed half of this control pass while "+
			"proving nothing", RenderACLKey(wellFormed.Action, wellFormed.Resource, wellFormed.ResourceName), err)
	}
}

