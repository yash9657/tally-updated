// TestLookupsAgreeWithTheRegistry exercises ByID / ByACLKey / Search against the
// generated rows, with a control on each so that a do-nothing implementation
// (return zero, return nil, return everything) cannot pass.
func TestLookupsAgreeWithTheRegistry(t *testing.T) {
	// ByID resolves a row that exists...
	if _, ok := ByID("post.vouchers.sales"); !ok {
		t.Error("ByID could not find post.vouchers.sales")
	}
	// ...and CONTROL: refuses one that does not. Without this, `return Specs[0], true`
	// would pass the line above.
	if s, ok := ByID("post.vouchers.definitely-not-a-class"); ok {
		t.Errorf("ByID invented a spec for an unknown id: %+v", s)
	}

	// ByACLKey is many-to-one by design; `create master` is the key several
	// master collections share, and collapsing it to one row is the failure the
	// slice return exists to prevent.
	masters := ByACLKey("create master")
	if len(masters) < 2 {
		t.Errorf("ByACLKey(\"create master\") returned %d spec(s); several master collection "+
			"routes share that one key, and a lookup that returns one of them would leave the "+
			"rest ungoverned by anything built on it", len(masters))
	}
	for _, s := range masters {
		if s.ACLKey != "create master" {
			t.Errorf("ByACLKey returned %s with key %q", s.ID, s.ACLKey)
		}
	}
	// CONTROL: an unknown key returns nothing, so ByACLKey is filtering rather
	// than returning the registry.
	if got := ByACLKey("create not-a-resource"); len(got) != 0 {
		t.Errorf("ByACLKey(\"create not-a-resource\") returned %d specs, want 0", len(got))
	}

	// Search narrows...
	hits := Search("day-book")
	if len(hits) == 0 {
		t.Error("Search(\"day-book\") found nothing")
	}
	for _, s := range hits {
		if !strings.Contains(strings.ToLower(s.ID+s.ACLKey+s.Label+s.UICommand), "day-book") {
			t.Errorf("Search returned %s, which does not contain the query", s.ID)
		}
	}
	// ...and CONTROL: it is a filter, not a passthrough. `return Specs` would
	// satisfy "found something" above.
	if len(hits) >= len(Specs) {
		t.Errorf("Search(\"day-book\") returned %d of %d specs; it is not filtering",
			len(hits), len(Specs))
	}
	// Search is ordered, because the W1 evals need it reproducible.
	if !sort.SliceIsSorted(hits, func(i, j int) bool { return hits[i].ID < hits[j].ID }) {
		t.Error("Search results are not sorted by id; an unstable ordering makes an eval " +
			"regression indistinguishable from noise")
	}
}

func formatCounts(m map[authz.Action]int) string {
	parts := make([]string, 0, len(m))
	for a, n := range m {
		parts = append(parts, fmt.Sprintf("%s=%d", a, n))
	}
	sort.Strings(parts)
	return strings.Join(parts, " ")
}
