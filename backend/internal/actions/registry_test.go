// insightd draft routes are driven by a worker — but it is the most dangerous
// kind of row in this registry, because it is a door into the books that no
// operator has ever walked through and therefore nobody has ever looked at. The
// agent layer will read this file and will happily walk through it.
//
// So the rule is testhygiene's declaredKeeps rule (hygiene_test.go:74 and its
// TestOptOutsAreDeclared at :464), applied to a door instead of a fixture:
// adding one forces the author to write down WHERE and WHY, in a file a reviewer
// reads, or the gate goes red. The alternative — letting an unreachable action
