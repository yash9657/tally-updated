// TestRegistryProvenanceIsComplete refuses a registry that was built from an
// incomplete set of sources.
//
// ⛔ THIS IS THE ASSERTION THAT STOPS THE COUNT FROM MASKING A HALF-BUILD. W0's
// deliverable is a coverage test failing CI on "any UI command without an action
// OR ANY ACTION WITHOUT A UI PATH". 230 route arms and zero UI commands
// satisfies every count in this file and proves precisely half of that — and the
// half it drops is the half nobody would notice was missing, because the number
// on the tin still reads 230.
//
// ⛔ AND IT FATALS RATHER THAN SKIPS WHEN THE FRONTEND MANIFEST IS ABSENT. A
// golden guarded by a skip is a golden that silently stops being checked
// (internal/compliance/tax_sections_golden_test.go:16); `go test` exits 0 on a
// skip, so CI would be green on a registry that knows nothing about the UI.
func TestRegistryProvenanceIsComplete(t *testing.T) {
	if Source.RouteArms == 0 {
		t.Fatal("Source.RouteArms is 0: the router walk contributed nothing. Every ACL key in " +
			"this registry comes from that walk, so a zero here means the rows (if any) were " +
			"not derived from routeAction at all")
	}
	if Source.RouteArms != len(Specs) {
		t.Errorf("Source.RouteArms = %d but there are %d specs. The registry and its provenance "+
			"were written by different runs; regenerate", Source.RouteArms, len(Specs))
	}

	if !Source.UIManifestPresent {
		t.Fatalf("this registry was generated WITHOUT %s, so it cannot answer the question W0 "+
			"commissioned it to answer.\n\n"+
			"  Source.Degradation: %s\n\n"+
			"Every spec is Channel %q, which is indistinguishable from \"nothing in the product "+
			"reaches any of these 230 actions\". That is not a state to skip past: a green run "+
			"here would certify a registry that proves half of nothing.\n\n"+
			"Lane E of W0 generates that manifest from the frontend keymap, screen actions and "+
			"client methods. Once it exists:\n"+
			"  UPDATE_GOLDENS=1 go test ./internal/server/ -run TestActionRegistryGolden",
			Source.UIManifestPath, Source.Degradation, ChannelNone)
	}
	if Source.Degradation != "" {
		t.Fatalf("this registry records a degradation and must not be relied on: %s", Source.Degradation)
	}
	// ⛔ THE JOIN HAS TWO HALVES AND AT LEAST ONE MUST HAVE LANDED. The manifest
	// carries a per-COMMAND `acl` claim (keystroke-level, the sharper answer) and
	// a `client_calls` census (which HTTP calls the shipped clients make, driven
	// against a recording transport). Today only the second exists — every row
	// below is Channel "client" — and that is stated in Provenance rather than
	// smoothed over: the registry proves that a route is reachable from the
	// running product, not which key reaches it. Zero from BOTH halves means the
	// paths changed shape and the generator matched none of them, which would
	// leave every action looking unreachable while the product works fine.
	if Source.UICommandsJoined == 0 && Source.ClientCallsJoined == 0 {
		t.Fatalf("%s was present but NOT ONE of its commands or client calls resolved to a "+
			"route in this registry. The join key is (verb, path) through the router; zero hits "+
			"means the manifest's paths changed shape and the generator matched none of them",
			Source.UIManifestPath)
	}
	// A floor on the client half, for the same reason every walker in this repo
	// carries one: 162 of the 165 recorded calls join today, and a number near
	// zero is a broken join wearing a working one's clothes.
	if Source.ClientCallsJoined > 0 && Source.ClientCallsJoined < 100 {
		t.Errorf("only %d client call(s) joined to a route, want >= 100 (162 did when this was "+
			"written). Either the frontend census shrank or the join stopped matching",
			Source.ClientCallsJoined)
	}
	t.Logf("provenance: %d route arms, %d UI commands joined, %d client calls joined "+
		"(%d skipped as calls to a method nothing in the app references)",
		Source.RouteArms, Source.UICommandsJoined, Source.ClientCallsJoined, Source.ClientCallsUnused)
}

// TestEveryActionHasAHumanPath is the W0 deliverable's second direction: no
// action without a UI path.
//
// ⚠️ READ ChannelClient BEFORE READING A PASS HERE AS MORE THAN IT IS. Today's
// evidence is that a method on one of the app's HTTP clients requests the route
// AND the app's own source references that method — "a person driving the
// product reaches it" — not "this key presses it". The keystroke-level claim
// needs `commands[].acl` in the frontend manifest, which is the remaining half
// of W0 lane E; the generator already reads it and prefers it, so those rows
// sharpen without a change here. What this test DOES catch, today, is the thing
// it was commissioned for: a route into the books that nothing in the product
// reaches, sitting in a registry the agent layer will read and walk through.
//
// It runs only on a complete build; TestRegistryProvenanceIsComplete owns the
// incomplete case and fails loudly there, so this one does not need to
// re-diagnose it (and must not, or one missing file produces two confusing
// failures).
func TestEveryActionHasAHumanPath(t *testing.T) {
	// ⚠️ IT DEFERS TO THE PROVENANCE TEST ON EVERY INCOMPLETE BUILD, AND THAT IS
	// NOT POLITENESS. Run against a registry with no UI data at all, the loop
	// below reports all 230 rows as "unreachable" — 230 lines of red whose real
	// cause is one missing input. A diagnosis that buries its own cause is a
	// diagnosis people learn to scroll past. One failure, in the place that knows
	// why.
	if !Source.UIManifestPresent || Source.Degradation != "" ||
		(Source.UICommandsJoined == 0 && Source.ClientCallsJoined == 0) {
		t.Fatalf("cannot evaluate: the registry was not built from a complete set of sources "+
			"(%s present=%t, commands joined=%d, client calls joined=%d).\n  %s\n\n"+
			"See TestRegistryProvenanceIsComplete, which owns this failure.",
			Source.UIManifestPath, Source.UIManifestPresent, Source.UICommandsJoined,
			Source.ClientCallsJoined, Source.Degradation)
	}

	var orphans []string
	for _, s := range Specs {
		if s.Channel != ChannelNone {
			continue
		}
		if _, declared := actionsWithNoHumanPathYet[s.ID]; declared {
			continue
		}
		orphans = append(orphans, fmt.Sprintf("%s  (%s %s -> %q)", s.ID, s.Method, s.Route, s.ACLKey))
	}
	sort.Strings(orphans)
	if len(orphans) > 0 {
		t.Errorf("%d action(s) that NOTHING in the UI reaches:\n  %s\n\n"+
			"Each one is a door into the books that no operator has walked through, which the "+
			"agent layer will read from this file and walk through happily. Either wire a "+
			"command to it, or add it to actionsWithNoHumanPathYet in this file WITH A WRITTEN "+
			"REASON (and raise maxActionsWithNoHumanPathYet in the same commit).",
			len(orphans), strings.Join(orphans, "\n  "))
	}
}

// TestNoHumanPathOptOutsAreDeclared keeps that escape hatch honest, in the three
// directions testhygiene's TestOptOutsAreDeclared keeps its own honest.
func TestNoHumanPathOptOutsAreDeclared(t *testing.T) {
	// ⚠️ THE SCANNED COUNT IS LOGGED BECAUSE ALL THREE CHECKS BELOW ARE WALKS
	// OVER ONE MAP, AND AN EMPTY MAP SATISFIES EVERY ONE OF THEM. That is not a
	// reason to Fatal on empty — an empty map is the STATE THIS PROJECT WANTS
	// (every mounted action reachable from the product), and a test that failed
	// when the work was finished would be a test people delete. It is a reason to
	// print the number, so a reader of a green log can tell "27 exemptions, each
	// checked three ways" from "nothing here ran".
	t.Logf("checking %d declared opt-out(s) against a ceiling of %d; at 0 this suite is inert "+
		"by design and the first entry anybody adds is what arms it",
		len(actionsWithNoHumanPathYet), maxActionsWithNoHumanPathYet)

	// (1) Every reason is actually written. An empty string is an exemption
	// nobody explained, which is the state the map exists to prevent.
	for id, reason := range actionsWithNoHumanPathYet {
		if strings.TrimSpace(reason) == "" {
			t.Errorf("actionsWithNoHumanPathYet[%q] has an EMPTY reason. The reason IS the "+
				"mechanism: an exemption with no explanation is indistinguishable from a "+
				"forgotten wiring job", id)
		}
	}

	// (2) The ceiling, recorded as an assertion rather than a comment so that
	// changing it is a deliberate edit to a test.
	if len(actionsWithNoHumanPathYet) > maxActionsWithNoHumanPathYet {
		t.Errorf("actionsWithNoHumanPathYet has %d entries, above the declared ceiling of %d.\n"+
			"If that is now genuinely right, change maxActionsWithNoHumanPathYet in the same "+
			"commit as the entries, and say in the message which routes are machine-to-machine "+
			"and why.", len(actionsWithNoHumanPathYet), maxActionsWithNoHumanPathYet)
	}

	// (3) The cross-check, copied from auth_stored_date_cutoff_test.go's route
	// ledger: an id that is BOTH reachable and listed as unreachable means one of
	// the two is wrong, and the dangerous reading is that somebody wired a UI
	// command to a route and left the pre-authorised exemption sitting under it.
	// Line entries go stale; a stale exemption is a blanket permission on a row
	// that now does something else.
	for id, reason := range actionsWithNoHumanPathYet {
		s, ok := ByID(id)
		if !ok {
			t.Errorf("actionsWithNoHumanPathYet lists %q (%q), which is not a spec id in this "+
				"registry. Routes move; a stale entry pre-authorises a row that no longer "+
				"exists — delete it", id, reason)
			continue
		}
		if s.Channel != ChannelNone {
			t.Errorf("%s is BOTH reachable from the UI (channel %q, command %q) AND listed in "+
				"actionsWithNoHumanPathYet as %q — one of the two is wrong. If the command is "+
				"real, delete the exemption; if the exemption is real, the join in the "+
				"generator is matching something it should not",
				id, s.Channel, s.UICommand, reason)
		}
	}
}

