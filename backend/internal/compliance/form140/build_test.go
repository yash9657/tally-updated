// TestBelowThresholdRentIsRefusedBecauseAnnexure6HasNoFlagForIt is the single
// most surprising thing the primary spec settled, and the reason reading it
// mattered.
//
// Rent has a threshold — ₹50,000 a month — so sub-threshold rent payments are
// ordinary. But Annexure 6 does not list codes 1008 or 1009 against flag Y
// ("payment below threshold limit"). A guessed implementation would have written
// Y there, produced a statement the FVU rejects, and only discovered it at the
// portal. This build refuses, and says what the legal flags actually are.
func TestBelowThresholdRentIsRefusedBecauseAnnexure6HasNoFlagForIt(t *testing.T) {
	for _, code := range []string{"1008", "1009"} {
		st := fixture()
		d := &st.Challans[0].Deductees[1]
		d.SectionCode = code
		d.ReasonFlag = "" // "the payment was below the threshold"

		_, err := form140.Build(st)
		if !errors.Is(err, form140.ErrNoValidReasonFlag) {
			t.Fatalf("section %s: want ErrNoValidReasonFlag, got %v", code, err)
		}
		if !strings.Contains(err.Error(), "does not permit the below-threshold flag Y") {
			t.Errorf("section %s: the refusal does not explain itself: %v", code, err)
		}
	}
	// And quoting Y anyway is refused too, rather than silently emitted.
	st := fixture()
	st.Challans[0].Deductees[1].SectionCode = "1009"
	st.Challans[0].Deductees[1].ReasonFlag = "Y"
	if _, err := form140.Build(st); err == nil ||
		!strings.Contains(err.Error(), "validity matrix does not permit that pair") {
		t.Errorf("quoting Y against 1009 should be refused by the matrix, got %v", err)
	}
}

// TestDirectorsFeesHaveNoBelowThresholdFlagAndTheStatuteAgrees is the same rule
// arriving from the other direction, and it is a genuine cross-check rather
// than a restatement.
//
// Annexure 6 omits 1028 from flag Y. Independently, compliance's rate table
// gives 194J-D a threshold basis of NIL, because s.393(1) [Table: Sl. No.
// 6(iii)] states the threshold for limb (c) as "Nil". Two documents read at
// different times by different means agree that a directors' fee cannot be
// below a threshold — which is the strongest evidence available here that both
// were read correctly.
func TestDirectorsFeesHaveNoBelowThresholdFlagAndTheStatuteAgrees(t *testing.T) {
	if form140.ReasonFlagValid("Y", "1028") {
		t.Error("Annexure 6 was transcribed with Y valid against 1028 (directors' fees)")
	}
	ruleset, err := compliance.LoadTDSRuleSet("tds-2026-04")
	if err != nil {
		t.Fatal(err)
	}
	got, err := compliance.TDSDerive(compliance.TDSInput{
		Section:       "194J-D",
		DeducteeType:  compliance.DeducteeOther,
		PANAvailable:  true,
		TaxableAmount: rs("1"),
	}, ruleset)
	if err != nil {
		t.Fatal(err)
	}
	if got.ReturnCode != "1028" {
		t.Fatalf("194J-D derives return code %q, want 1028", got.ReturnCode)
	}
	if got.Basis != compliance.BasisNil {
		t.Errorf("194J-D has threshold basis %q; the statute says Nil, which is why Annexure 6 "+
			"lists no below-threshold flag for its code", got.Basis)
	}
}

// TestEveryShippedReturnCodeIsInAnnexure2 walks compliance's ruleset and checks
// that every code it can produce is one the return can carry.
//
// A code the engine emits and the annexure does not know is a statement the
// department rejects — discovered at the portal, per deductee, months after the
// deduction.
func TestEveryShippedReturnCodeIsInAnnexure2(t *testing.T) {
	ruleset, err := compliance.LoadTDSRuleSet("tds-2026-04")
	if err != nil {
		t.Fatal(err)
	}
	for _, section := range compliance.TDSSections(ruleset) {
		for _, dt := range []string{compliance.DeducteeIndHUF, compliance.DeducteeOther} {
			code, err := compliance.TDSReturnCode(section, dt)
			if err != nil {
				t.Errorf("%s/%s has no return code: %v", section, dt, err)
				continue
			}
			if _, ok := form140.PaymentCodes[code]; !ok {
				t.Errorf("%s/%s derives code %q, which is not in Annexure 2", section, dt, code)
			}
		}
	}
}

// TestWhichShippedSectionsCanReportASubThresholdPayment records, as an
// assertion rather than as prose, exactly which of the engine's sections can
// carry a below-threshold payment into the return and which cannot.
//
// It is here so that adding a section to compliance's ruleset without checking
// Annexure 6 fails a test instead of failing at the portal. THE TWO RENT
// SECTIONS ARE THE PROBLEM CASES and they are named, not hidden behind a loop.
func TestWhichShippedSectionsCanReportASubThresholdPayment(t *testing.T) {
	want := map[string]bool{
		"194C":   true,  // 1023 / 1024
		"194J-P": true,  // 1027
		"194J-T": true,  // 1026
		"194H":   true,  // 1006
		"194J-D": false, // 1028 — threshold is Nil, so Y cannot arise
		"194I-A": false, // 1008 — rent HAS a threshold, and Y is still not listed
		"194I-B": false, // 1009 — likewise
	}
	ruleset, err := compliance.LoadTDSRuleSet("tds-2026-04")
	if err != nil {
		t.Fatal(err)
	}
	sections := compliance.TDSSections(ruleset)
	if len(sections) != len(want) {
		t.Fatalf("the ruleset ships %d sections and this test knows %d; check Annexure 6 for the "+
			"new one before adding it here", len(sections), len(want))
	}
	for _, section := range sections {
		code, err := compliance.TDSReturnCode(section, compliance.DeducteeOther)
		if err != nil {
			t.Fatal(err)
		}
		if got := form140.ReasonFlagValid("Y", code); got != want[section] {
			t.Errorf("%s (code %s): Y valid = %v, want %v", section, code, got, want[section])
		}
	}
}

