// TestTotalsAreComputedFromTheRecordsTheyHead: the batch total, the challan
// deposit total and the two annexure totals are all summed here rather than
// accepted from the caller, so a total that disagrees with its rows is not
// expressible.
func TestTotalsAreComputedFromTheRecordsTheyHead(t *testing.T) {
	out, err := form140.Build(fixture())
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSuffix(string(out), "\r\n"), "\r\n")
	bh := strings.Split(lines[1], "^")
	if bh[46] != "1500.00" { // BH field 47, batch total of deposits
		t.Errorf("batch deposit total is %q, want 1500.00", bh[46])
	}
	cd := strings.Split(lines[2], "^")
	if cd[11] != "1500.00" { // CD field 12 = 8+9+10+11
		t.Errorf("challan deposit total is %q, want 1500.00", cd[11])
	}
	if cd[20] != "1500.00" || cd[21] != "1500.00" { // CD 21, 22 vs the annexure
		t.Errorf("challan annexure totals are %q/%q, want 1500.00/1500.00", cd[20], cd[21])
	}
	if cd[4] != "2" { // CD field 5, count of deductee records
		t.Errorf("deductee count is %q, want 2", cd[4])
	}
}

// TestTheRateIsWrittenAtFourDecimals is General Note 5 — "if the rate is 2 then
// the same should be mentioned as 2.0000" — and it is the reason
// tds_deduction.rate_pct is NUMERIC(9,4).
func TestTheRateIsWrittenAtFourDecimals(t *testing.T) {
	out, err := form140.Build(fixture())
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSuffix(string(out), "\r\n"), "\r\n")
	dd := strings.Split(lines[3], "^")
	if dd[27] != "2.0000" { // DD field 28
		t.Errorf("rate is %q, want 2.0000", dd[27])
	}
	if dd[19] != "75000.00" { // DD field 20, amount paid, at two decimals
		t.Errorf("amount paid is %q, want 75000.00", dd[19])
	}
	// The zero-tax record: rate 0.0000, and no date of deduction at all.
	zero := strings.Split(lines[4], "^")
	if zero[27] != "0.0000" {
		t.Errorf("zero-tax rate is %q, want 0.0000", zero[27])
	}
	if zero[26] != "" { // DD field 27
		t.Errorf("zero-tax record carries date of deduction %q, want empty", zero[26])
	}
}

// TestTheFormatVersionIsPinned is invariant I-7 of docs/design/t6-model.md §4
// in one assertion: no file without a format version traced to a read primary
// source, and the emptiness of that string is what used to make the refusal
// correct.
func TestTheFormatVersionIsPinned(t *testing.T) {
	if form140.FormatVersion == "" {
		t.Fatal("FormatVersion is empty; I-7 forbids emitting a file")
	}
	if form140.FormatVersion != "1.0" {
		t.Errorf("FormatVersion is %q, want 1.0 — the version on the workbook's title row",
			form140.FormatVersion)
	}
	if !strings.Contains(form140.FormatSource, "form-140-file-format.xlsx") {
		t.Error("FormatSource does not name the document it was read from; a version number with " +
			"no document behind it is not a citation")
	}
}
