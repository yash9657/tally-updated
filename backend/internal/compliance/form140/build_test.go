// TestGoldenFile is the only test that asserts the WHOLE byte sequence.
//
// testdata/q2-2026-27.txt was generated by this package and then read line by
// line against the workbook's four field tables. Regenerate it with -update ONLY
// after checking the diff against the spec — a golden file that is refreshed
// because it changed proves nothing.
func TestGoldenFile(t *testing.T) {
	got, err := form140.Build(fixture())
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	path := filepath.Join("testdata", "q2-2026-27.txt")
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(path, got, 0o644); err != nil {
			t.Fatal(err)
		}
		t.Fatalf("golden file rewritten; re-read %s against the workbook before committing", path)
	}
	want, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(want) {
		t.Errorf("emitted file differs from the golden file.\n--- got ---\n%q\n--- want ---\n%q",
			got, want)
	}
}

// TestDelimiterCountIsOneLessThanFieldCount is General Note 10, checked on real
// output rather than on the tables.
//
// It is the invariant the whole layout design exists to make unbreakable, so it
// is asserted on the bytes: a record with one delimiter too few shifts every
// later column, which is silent in Go and fatal at the portal.
func TestDelimiterCountIsOneLessThanFieldCount(t *testing.T) {
	out, err := form140.Build(fixture())
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	want := map[string]int{"FH": 17, "BH": 71, "CD": 29, "DD": 44}
	lines := strings.Split(strings.TrimSuffix(string(out), "\r\n"), "\r\n")
	if len(lines) != 6 { // FH, BH, CD, DD, DD, CD, DD -> 7
		t.Logf("file has %d records", len(lines))
	}
	seen := map[string]int{}
	for i, line := range lines {
		parts := strings.Split(line, "^")
		typ := parts[1]
		seen[typ]++
		if got := strings.Count(line, "^"); got != want[typ] {
			t.Errorf("record %d (%s) carries %d delimiters, want %d", i+1, typ, got, want[typ])
		}
	}
	for _, typ := range []string{"FH", "BH", "CD", "DD"} {
		if seen[typ] == 0 {
			t.Errorf("no %s record was emitted; the test proves nothing about it", typ)
		}
	}
}

// TestEveryRecordEndsWithCRLF is General Note 2, including its "(including last
// record)" clause — the file ends with a terminator and there is no trailing
// empty record.
func TestEveryRecordEndsWithCRLF(t *testing.T) {
	out, err := form140.Build(fixture())
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	s := string(out)
	if !strings.HasSuffix(s, "\r\n") {
		t.Error("the file does not end with CRLF")
	}
	if strings.HasSuffix(s, "\r\n\r\n") {
		t.Error("the file ends with a blank record")
	}
	if strings.Contains(strings.ReplaceAll(s, "\r\n", ""), "\n") {
		t.Error("a bare LF appears outside a CRLF pair")
	}
	// Line numbers run 1..N across the whole file, not per record type.
	for i, line := range strings.Split(strings.TrimSuffix(s, "\r\n"), "\r\n") {
		if got := strings.SplitN(line, "^", 2)[0]; got != itoa(i+1) {
			t.Errorf("record %d carries line number %q", i+1, got)
		}
	}
}

func itoa(i int) string { return decimal.NewFromInt(int64(i)).String() }

