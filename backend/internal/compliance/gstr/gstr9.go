// ErrInvalid9 reports a generated GSTR-9 that violates one of this file's own
// honesty rules.
var ErrInvalid9 = fmt.Errorf("gstr: generated GSTR-9 violates a validation rule")

// ErrPeriodsFailed reports that one or more of the twelve periods behind a
// GSTR-9 could not be generated. It is its OWN sentinel rather than a wrap of
// whatever the first month returned: when three periods fail for three
// different reasons, errors.Is on any one of them is a coin toss, and a caller
// that branched on it would act on a reason that applies to one twelfth of the
// problem.
//
// ⚠️ ITS MESSAGE CARRIES NO `gstr: ` PACKAGE PREFIX, unlike ErrInvalid3B and
// ErrInvalid9 above. That is deliberate and it is the D93 rule applied to this
// file's own new text: this sentence is composed for an OPERATOR, and prefixing
// it with a Go package name is the first half of the very stack operatorMessage
// exists to undo. (The two older sentinels keep theirs; changing a message that
// is already on the wire for /gstr1 and /gstr3b is not this change's to make.)
var ErrPeriodsFailed = fmt.Errorf("GSTR-9 periods could not be generated")

// operatorMessage flattens the package prefixes off an internal error so the
// sentence an operator reads begins with something they can act on.
//
// The wraps stack three deep by the time a monthly 3B failure reaches the
// annual return: "gstr3b: gstr: generated GSTR-3B violates a validation rule:
// ...". Each of those prefixes names a Go package, which tells the reader
// nothing about what they may do — D93 is this exact class, closed on those
// grounds for masters.CreateLedger.
//
// ⚠️ IT TRIMS PACKAGE NAMES ONLY. "generated GSTR-3B violates a validation
// rule" survives, because that names a STATUTORY document and a real condition;
// "output-tax postings" survives for the same reason. The test for whether a
// prefix belongs here is whether it would appear on the return.
func operatorMessage(err error) string {
	s := err.Error()
	for {
		trimmed := s
		for _, p := range []string{"gstr: ", "gstr1: ", "gstr3b: ", "gstr9: "} {
			trimmed = strings.TrimPrefix(trimmed, p)
		}
		if trimmed == s {
			return s
		}
		s = trimmed
	}
}

// Validate9 enforces the properties this report's usefulness rests on. It runs
// on every Generate9 rather than only in tests, because the failure it guards
// against — a table with a blank reason, a suppressed total with no explanation
// in its place — is invisible in the output and looks exactly like a correct
// report to the reader it misleads.
func Validate9(g GSTR9) error {
	if len(g.Months) != 12 {
		return fmt.Errorf("%w: a financial year has 12 periods, got %d — a month missing from the "+
			"grid is a month nobody checked", ErrInvalid9, len(g.Months))
	}
	known := map[string]bool{}
	for _, d := range KnownDisclosures9 {
		known[d] = true
	}
	for _, d := range g.Disclosures {
		if !known[d] {
			return fmt.Errorf("%w: disclosure %q is not in KnownDisclosures9. A frontend switches on "+
				"these strings, so an unrecognised one is silently invisible", ErrInvalid9, d)
		}
	}
	for _, t := range g.Tables {
		if t.Status != TableDerived && strings.TrimSpace(t.Reason) == "" {
			return fmt.Errorf("%w: table %s is %s with no reason. A blank space where a statutory "+
				"figure belongs is read as zero", ErrInvalid9, t.No, t.Status)
		}
		if t.Status == TableNotDerived && len(t.Rows) > 0 {
			return fmt.Errorf("%w: table %s is NOT_DERIVED but carries %d rows — NOT_DERIVED means "+
				"no rows, not zero rows", ErrInvalid9, t.No, len(t.Rows))
		}
		if t.Status == TablePartial && len(t.Omitted) == 0 {
			return fmt.Errorf("%w: table %s is PARTIAL but names nothing omitted; PARTIAL without a "+
				"list of what is missing tells the reader less than DERIVED would", ErrInvalid9, t.No)
		}
		if t.TotalSuppressed && strings.TrimSpace(t.TotalSuppressedReason) == "" {
			return fmt.Errorf("%w: table %s suppresses its total with no reason printed in its "+
				"place", ErrInvalid9, t.No)
		}
	}
	// ⛔ THE CENTRAL INVARIANT. Gross can never be less than |Net| — it is a sum
	// of absolute values of the same terms — and if it EQUALS |Net| in every
	// head then nothing offset. A Divergence claiming otherwise means the
	// accumulation was written as |sum| somewhere, which is the mutation this
	// file's header warns about.
	for _, d := range []Divergence{g.OutwardR1VsR3B, g.OutwardR3BVsBooks, g.OutwardR1VsBooks,
		g.ITCVsBooks, g.HSNVsR1} {
		n := absTax(d.Net)
		if n.CGST.GreaterThan(d.Gross.CGST) || n.SGST.GreaterThan(d.Gross.SGST) || n.IGST.GreaterThan(d.Gross.IGST) {
			return fmt.Errorf("%w: %s vs %s reports a net larger than its gross, which is "+
				"arithmetically impossible: the gross is a sum of absolute values of the same "+
				"monthly terms", ErrInvalid9, d.A, d.B)
		}
		if d.Offsetting == n.Equal(d.Gross) {
			return fmt.Errorf("%w: %s vs %s sets offsetting=%v while |net| %s gross — offsetting "+
				"means exactly that the two differ", ErrInvalid9, d.A, d.B, d.Offsetting,
				map[bool]string{true: "equals", false: "does not equal"}[n.Equal(d.Gross)])
		}
		if d.Agrees != (len(d.Months) == 0) {
			return fmt.Errorf("%w: %s vs %s claims agrees=%v while naming %d disagreeing months. "+
				"Agreement is a per-month property and must never be read off the annual net",
				ErrInvalid9, d.A, d.B, d.Agrees, len(d.Months))
		}
	}
	return nil
}
