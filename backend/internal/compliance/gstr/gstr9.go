// gstr9.go builds the GSTR-9 ANNUAL RETURN for one Indian financial year.
//
// ===========================================================================
// THIS IS A RECONCILIATION, NOT A DERIVATION, AND THAT DECIDES EVERYTHING
// ===========================================================================
// GSTR-1 and GSTR-3B are DERIVED here: each reads the immutable voucher log for
// a month and states what it finds. GSTR-9 is not that. It is the document that
// asks whether the year's FILED RETURNS and the BOOKS tell the same story, and
// its only real content is the places where they do not.
//
// So this file does NOT re-derive the year from the voucher log. Deriving it
// afresh would produce a fourth number that agrees with nothing, and an annual
// return generated by summing twelve months and calling it done is precisely
// what PLAN-TALLY-PARITY.md's T12 row says this must not be.
//
// It runs the EXISTING generators month by month and puts THREE INDEPENDENT
// COMPUTATIONS of the same year side by side:
//
//	(1) GSTR-1        Service.Generate     — classifies each Sales voucher into
//	                                         B2B / B2CL / B2CS / CDNR and rolls
//	                                         the sections up.
//	(2) GSTR-3B       Service.Generate3B   — issues its OWN SQL over the same
//	                                         voucher log (gstr3b.go's header
//	                                         says why it must not delegate).
//	(3) THE BOOKS     PostingTaxTotals /   — sums the POSTINGS on the named
//	                  ITCPostingTotals       tax ledgers. A different table, a
//	                                         different key, a different query.
//
// Three paths that must land on one number. When they do not, the disagreement
// IS the report.
//
// ===========================================================================
// ⭐ THE ONE RULE THIS REPORT LIVES OR DIES ON: A NET DIFFERENCE IS A LIE
// ===========================================================================
// An annual return is twelve months added up, and addition CANCELS. A company
// that over-declared 40,000 of IGST in May and under-declared 40,000 in
// September has an annual net difference of ZERO. Every figure foots. Every
// total is correct. And the return is confidently, silently wrong about the one
// thing it exists to say.
//
// So NO DIFFERENCE IS EVER REPORTED AS A NET ALONE. Every comparison in this
// file carries THREE things:
//
//	Net    sum over months of (A - B)          — cancels, and is the figure a
//	                                             filer would otherwise see alone
//	Gross  sum over months of |A - B|          — cannot cancel
//	Months the FPs where the two disagree      — so the reader can go and look
//
// and when Gross is not equal to |Net| head for head, `Offsetting` is TRUE, the
// `monthly-differences-offset` disclosure fires, and the screen prints the
// months instead of the reassuring zero. This is the same discipline
// budget_variance.go applies with `totals_are_addable`: a figure that cannot be
// honestly stated is SUPPRESSED and the reason is printed in its place, never
// left as a plausible zero.
//
// ===========================================================================
// WHAT IS DERIVED, WHAT IS NOT, AND WHY EVERY GAP IS A NAMED TABLE
// ===========================================================================
// The statutory GSTR-9 has tables 4 through 19. Most of them cannot be built
// from these books, and the honest answer is to say which and why — not to emit
// a zero. A zero in table 7 ("ITC reversed") is indistinguishable from a
// taxpayer who reversed nothing, and that is a wrong number in real tax.
//
// Every table below appears in the output with a STATUS. `Tables` is the list;
// TableDerived / TablePartial / TableNotDerived are the three answers, and a
// NotDerived or Partial table carries a `reason` naming the missing input.
//
// ⛔ TABLE 4N IS SUPPRESSED EVEN THOUGH ITS COMPONENTS ARE PRESENT. 4N is the
// total of 4A..4L, four of whose rows this build cannot produce (exports, SEZ,
// deemed exports, advances). A total over a set with known-missing members is
// not a total; it is an understatement that looks like one. Same call, same
// reason, as the mixed-basis grand total in budget_variance.go.
//
// ===========================================================================
// ⛔ NOT FILING-READY, AND THE RESEARCH BEHIND IT IS ZERO
// ===========================================================================
// RESEARCH.md does not mention GSTR-9 anywhere — not once, not in passing
// (`grep -c -i "gstr-9" RESEARCH.md` -> 0). The table numbering and titles below
// were written from the return's published structure as generally understood and
// have NOT been verified against the CBIC notification or the GSTN offline
// utility's schema, and the portal is not reachable from this build to check
// (the IRP hosts are geo-fenced). `annual-table-structure-unverified` and
// `portal-schema-unverified` are therefore UNCONDITIONAL: every GSTR-9 this
// build produces carries them, and therefore carries `not-filing-ready` too.
//
// THIS IS A RECONCILIATION WORKPAPER. It is genuinely useful for finding the
// month where the returns and the books parted company, which is the job an
// accountant actually does before filing. It is not an upload artifact and
// nothing here claims it is.
//
// ===========================================================================
// WHY THE BOOKS COLUMN IS REQUIRED RATHER THAN OPTIONAL
// ===========================================================================
// /gstr1 and /gstr3b both make the tax-ledger ids optional, because a RETURN is
// a legitimate thing to generate without reconciling it. GSTR-9 is not a return
// in that sense — it IS the reconciliation. Generated without the ledger ids,
// PostingTaxTotals would return zero for every head, every month would appear to
// disagree with the books by exactly the tax charged, and the one number a
// filer would take away is nonsense.
//
// So Generate9 REFUSES a missing ledger id, naming the ones it wants
// (ErrLedgersRequired). Refusing is the same call apportionment() makes about a
// missing rule-42 F: a zero reversal is indistinguishable from a correct one.
package gstr

import (
	"context"
	"fmt"
	"sort"
	"strings"
	"time"

	"github.com/google/uuid"
	"github.com/shopspring/decimal"
)

// ---------------------------------------------------------------------------
// ERRORS
