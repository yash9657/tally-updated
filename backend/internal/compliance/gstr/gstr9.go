// ErrNotAFinancialYear reports a window that is not an Indian financial year.
//
// GSTR-9 IS AN ANNUAL RETURN FOR A FINANCIAL YEAR and there is no such document
// as "the GSTR-9 for June to August". Generating one would put a real-looking
// statutory artifact in a filer's hands for a period the law does not recognise,
// which is worse than the refusal — so the window is checked before anything is
// read, and the message names the two dates that would work.
var ErrNotAFinancialYear = fmt.Errorf("gstr: GSTR-9 covers an Indian financial year (1 April to 31 March)")

// ErrLedgersRequired reports a GSTR-9 asked for without the tax ledger ids.
// See the file header: without them the books column is silently zero, and a
// books column of zeros makes every month look wrong by exactly the tax charged.
var ErrLedgersRequired = fmt.Errorf("gstr: GSTR-9 is a reconciliation TO the books and needs the tax ledger ids")

// ---------------------------------------------------------------------------
// THE CLOSED DISCLOSURE VOCABULARY
// ---------------------------------------------------------------------------
// A SEPARATE LIST FROM KnownDisclosures, DELIBERATELY. The 3B vocabulary
// describes a monthly return's gaps; these describe an annual reconciliation's,
// and they are not the same gaps. Merging them would force every 3B consumer to
// learn tokens that can never appear on a 3B, and — the direction that actually
// costs something — would let a GSTR-9 gap be added to the shared list and go
// unrendered by a frontend that only switches on the 3B set.
//
// The rule is the same one the 3B block states: the frontend SWITCHES on these
// strings, so a token it does not recognise is silently invisible, which is the
// exact failure the field exists to prevent. Validate9 refuses an unknown token.

const (
	// Disc9TableStructureUnverified — the table numbering and titles were not
	// verified against the CBIC notification or the GSTN offline utility.
	// UNCONDITIONAL. See the file header.
	Disc9TableStructureUnverified = "annual-table-structure-unverified"
	// Disc9PortalSchemaUnverified — the JSON key names are not the portal's.
	// UNCONDITIONAL, and it is spelled identically to the 3B token on purpose:
	// it means the same thing, and a frontend that already renders it should
	// render it here.
	Disc9PortalSchemaUnverified = "portal-schema-unverified"
	// Disc9ReversalsNotComputed — the twelve 3Bs behind this return were
	// generated with NO inward statement, so table 4(B) is empty in every one of
	// them and GSTR-9 table 7 is NOT DERIVED rather than zero. UNCONDITIONAL in
	// this slice: Generate9 does not take a statement (see monthlyOptions).
	Disc9ReversalsNotComputed = "itc-reversals-not-computed"
	// Disc9ExemptNotMarked — the books carry no export / SEZ / nil-rated /
	// exempt / non-GST marker, so tables 5, 4C, 4D and 4E cannot be produced.
	// UNCONDITIONAL, and it is the same gap gstr3b.go records for 3.1(b)/(c)/(e).
	Disc9ExemptNotMarked = "exempt-and-zero-rated-not-marked"
	// Disc9AdvancesNotModelled — no advance-receipt or adjustment store, so
	// table 4F and table 11 cannot be produced. UNCONDITIONAL.
	Disc9AdvancesNotModelled = "advances-not-modelled"
	// Disc9AmendmentsNotModelled — nothing records that a document was AMENDED
	// in a later return, so tables 4K/4L and 10-14 cannot be produced. An ALTER
	// here appends a version in the ORIGINAL period; it is not a return-side
	// amendment. UNCONDITIONAL.
	Disc9AmendmentsNotModelled = "amendments-not-modelled"
	// Disc9NoCashLedger — there is no electronic cash or credit ledger and no
	// GST challan register, so tables 9, 14 and 19 (tax and late fee actually
	// PAID) cannot be produced. UNCONDITIONAL.
	Disc9NoCashLedger = "no-cash-or-credit-ledger"
	// Disc9NoAnnual2A — the department's own annual GSTR-2A is not held, so
	// table 8 cannot be produced. UNCONDITIONAL. ⛔ 8D is 8A minus 8B: computing
	// 8B alone and reporting 8D as zero would assert perfect agreement with a
	// statement that was never read.
	Disc9NoAnnual2A = "no-annual-2a"
	// Disc9BooksCarryNoTaxableValue — the third column compares TAX only. The
	// books post tax to ledgers; taxable value is not a posted quantity, so
	// there is no books-side opinion on it and the taxable-value comparison is
	// GSTR-1 against GSTR-3B only. UNCONDITIONAL, and it is why
	// TaxableDivergence exists as its own field rather than a third column.
	Disc9BooksCarryNoTaxableValue = "books-carry-no-taxable-value"
	// Disc9MonthsOffset — CONDITIONAL, and the only conditional token here. At
	// least one comparison has months that cancel: its gross divergence exceeds
	// the absolute value of its net. The annual net for that comparison is a
	// number that HIDES a disagreement, and the months are named.
	Disc9MonthsOffset = "monthly-differences-offset"
	// Disc9ReturnsDisagree — CONDITIONAL. At least one comparison is non-zero
	// somewhere in the year: the returns and the books, or the two returns, do
	// not tell the same story. This is the token a frontend needs to refuse to
	// present the year as reconciled.
	Disc9ReturnsDisagree = "returns-and-books-disagree"
	// Disc9NotFilingReady is emitted whenever ANY other token is present —
	// which, because seven of them are unconditional, is ALWAYS. It is stated
	// anyway rather than hard-coded, so that if a later slice closes every gap
	// the flag goes away by itself instead of lying.
	Disc9NotFilingReady = "not-filing-ready"
)

// KnownDisclosures9 is the closed GSTR-9 vocabulary, for validation and for a
