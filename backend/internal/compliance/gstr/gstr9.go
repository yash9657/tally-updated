// Generate9 builds the annual reconciliation for the financial year [from, to].
//
// It runs FOUR reads per month — GSTR-1, GSTR-3B, the output-tax postings and
// the input-tax postings — for twelve months, so forty-eight reads in all. That
// is deliberate and is not an oversight to be optimised away by widening the
// monthly queries to a year: the twelve-month grid IS the report, and a single
// annual query cannot say which month broke.
//
// ⛔ NO ITCSource IS PASSED. GSTR-9 covers twelve periods and an inward
// statement is per period, so there is no single statement to reconcile the year
// against; compliance/itc refuses a window longer than one period for exactly
// that reason. The consequence is stated rather than hidden: table 4(B) is empty
// in all twelve 3Bs, GSTR-9 table 7 is NOT_DERIVED rather than zero, and
// `itc-reversals-not-computed` is unconditional.
func (s *Service) Generate9(ctx context.Context, from, to string, opts Options3B) (GSTR9, error) {
	startYear, label, err := financialYear(from, to)
	if err != nil {
		return GSTR9{}, err
	}
	if err := requireLedgers(opts); err != nil {
		return GSTR9{}, err
	}

	g := GSTR9{
		GSTIN:  opts.GSTIN,
		FY:     label,
		From:   from,
		To:     to,
		Months: make([]Month9, 0, 12),
	}

	// ⛔ EVERY MONTH IS ATTEMPTED, EVEN AFTER ONE FAILS.
	//
	// This loop used to return on the FIRST failing period. A twelve-month
	// report that dies on month four and names only month four tells the
	// operator to go and fix one month, and they discover the next one only by
	// running the report again — four times, if four are broken. The period was
	// already named ("which month failed" is the first thing anybody asks); the
	// gap was that it named exactly one.
	var failures []string
	for n := 0; n < 12; n++ {
		mFrom, mTo, fp := monthWindow(startYear, n)
		m, err := s.month9(ctx, mFrom, mTo, fp, opts)
		if err != nil {
			failures = append(failures, fmt.Sprintf("%s: %s", fp, operatorMessage(err)))
			continue
		}
		g.Months = append(g.Months, m)
	}
	if len(failures) > 0 {
		// ⛔ THE YEAR IS REFUSED, NOT EMITTED WITH A HOLE. Returning the months
		// that did work would put a statutory twelve-month grid in a filer's
		// hands with periods silently missing, and every annual total computed
		// over it would be understated by exactly the months nobody could see —
		// a wrong number that looks like a right one. Validate9 already refuses
		// a grid that is not twelve months for this reason. What changes here is
		// that the refusal names ALL of them.
		return GSTR9{}, fmt.Errorf("%w: %d of the 12 periods of %s failed (%d generated "+
			"cleanly), so the annual return cannot be produced. Each failing period and its "+
			"reason: %s",
			ErrPeriodsFailed, len(failures), label, 12-len(failures), strings.Join(failures, " | "))
	}

	g.OutwardR1VsR3B = divergence("gstr1", "gstr3b", g.Months,
		func(m Month9) (TaxTotals, TaxTotals) { return m.R1Tax, m.R3BTax })
	g.OutwardR3BVsBooks = divergence("gstr3b", "books", g.Months,
		func(m Month9) (TaxTotals, TaxTotals) { return m.R3BTax, m.BooksOutwardTax })
	g.OutwardR1VsBooks = divergence("gstr1", "books", g.Months,
		func(m Month9) (TaxTotals, TaxTotals) { return m.R1Tax, m.BooksOutwardTax })
	g.ITCVsBooks = divergence("gstr3b-4a-plus-4d", "books", g.Months,
		func(m Month9) (TaxTotals, TaxTotals) {
			return addTax(m.R3BITCAvailable, m.R3BITCIneligible), m.BooksITCTax
		})
	g.HSNVsR1 = divergence("gstr1-table-12", "gstr1-sections", g.Months,
		func(m Month9) (TaxTotals, TaxTotals) { return m.HSNTax, m.R1Tax })
	g.TaxableR1VsR3B = taxableDivergence("gstr1", "gstr3b", g.Months)

	g.Tables = buildTables9(g)
	g.Disclosures = disclosures9(g)

	if err := Validate9(g); err != nil {
		return GSTR9{}, err
	}
	return g, nil
}

// requireLedgers refuses a GSTR-9 that cannot have a books column, naming every
// missing parameter at once rather than one per round trip.
func requireLedgers(opts Options3B) error {
	var missing []string
	for _, p := range []struct {
		name string
		id   uuid.UUID
	}{
		{"cgst_ledger_id", opts.CGSTLedgerID},
		{"sgst_ledger_id", opts.SGSTLedgerID},
		{"igst_ledger_id", opts.IGSTLedgerID},
		{"input_cgst_ledger_id", opts.InputCGSTLedgerID},
		{"input_sgst_ledger_id", opts.InputSGSTLedgerID},
		{"input_igst_ledger_id", opts.InputIGSTLedgerID},
	} {
		if p.id == uuid.Nil {
			missing = append(missing, p.name)
		}
	}
	if len(missing) == 0 {
		return nil
	}
	return fmt.Errorf("%w: %s. Without them the books column is ZERO for every month "+
		"and every period appears to disagree with the returns by exactly the tax charged, "+
		"which is a wrong number that looks like a finding",
		ErrLedgersRequired, strings.Join(missing, ", "))
}

// month9 assembles one month's three sources.
func (s *Service) month9(ctx context.Context, from, to, fp string, opts Options3B) (Month9, error) {
	r1, err := s.Generate(ctx, from, to, opts.Options)
	if err != nil {
		return Month9{}, fmt.Errorf("gstr1: %w", err)
	}
	r3b, err := s.Generate3B(ctx, from, to, monthlyOptions(opts))
	if err != nil {
		return Month9{}, fmt.Errorf("gstr3b: %w", err)
	}
	outPosted, err := s.PostingTaxTotals(ctx, from, to, opts.Options)
	if err != nil {
		return Month9{}, fmt.Errorf("output-tax postings: %w", err)
	}
	itcPosted, err := s.ITCPostingTotals(ctx, from, to, opts)
	if err != nil {
		return Month9{}, fmt.Errorf("input-tax postings: %w", err)
	}

	m := Month9{
		FP:               fp,
		From:             from,
		To:               to,
		R1Txval:          outwardTaxable(r1),
		R1Tax:            r1.TaxTotals(),
		R3BTxval:         r3b.T31.OsupDet.Txval,
		R3BTax:           r3b.OutwardTax(),
		BooksOutwardTax:  outPosted,
		R3BITCAvailable:  sumTable4(r3b.T4.ItcAvl),
		R3BITCIneligible: sumTable4(r3b.T4.ItcInelg),
		BooksITCTax:      itcPosted,
		HSNTxval:         hsnTxval(r1),
		HSNTax:           hsnTax(r1),
		HSN:              r1.HSN.Data,
	}
	m.R1MatchesR3B = m.R1Tax.Equal(m.R3BTax)
	m.R3BMatchesBooks = m.R3BTax.Equal(m.BooksOutwardTax)
	m.ITCMatchesBooks = addTax(m.R3BITCAvailable, m.R3BITCIneligible).Equal(m.BooksITCTax)
	m.HSNFootsToR1 = m.HSNTax.Equal(m.R1Tax)
	return m, nil
}

// monthlyOptions strips the ITC seam from the options handed to the monthly 3B.
//
// ⛔ IT IS NOT A DEFENSIVE COPY, IT IS THE DECISION. Generate9's contract is
// that the twelve 3Bs behind the year are the BARE ones — no statement, no
// eligibility classification, nothing reversed — and that this is DISCLOSED
// rather than silently true. Passing a caller's ITCSource through would make
// the disclosure a lie for eleven of the twelve months, because a statement
// belongs to ONE period. If a later slice wants statement-backed annual ITC it
// needs a statement PER MONTH, which is a different signature and a different
// decision.
func monthlyOptions(opts Options3B) Options3B {
	out := opts
	out.ITC = nil
	out.ITCPolicy = nil
	return out
}

// outwardTaxable sums the taxable value across every section of a GSTR-1,
// signing credit notes negative exactly as GSTR1.TaxTotals signs their tax. A
// month with a sales return reports LESS outward value, and a taxable-value
// total that did not sign the note would disagree with a tax total that did —
// producing a divergence that is an artefact of this function rather than a
// fact about the books.
func outwardTaxable(g GSTR1) decimal.Decimal {
	t := decimal.Zero
	for _, p := range g.B2B {
		for _, inv := range p.Inv {
			for _, it := range inv.Itms {
				t = t.Add(it.ItmDet.Txval)
			}
		}
	}
	for _, p := range g.B2CL {
		for _, inv := range p.Inv {
			for _, it := range inv.Itms {
				t = t.Add(it.ItmDet.Txval)
			}
		}
	}
	for _, b := range g.B2CS {
		t = t.Add(b.Txval)
	}
	for _, p := range g.CDNR {
		for _, n := range p.Nt {
			sign := decimal.NewFromInt(-1)
			if n.Ntty == "D" {
				sign = decimal.NewFromInt(1)
			}
			for _, it := range n.Itms {
				t = t.Add(it.ItmDet.Txval.Mul(sign))
			}
		}
	}
	return t
}

// hsnTxval and hsnTax roll the GSTR-1 table-12 buckets back up to one figure.
//
// THEY DO NOT RE-SIGN ANYTHING. loadHSNRows already signs a credit note
// negative in SQL (`CASE WHEN vt.parent_class = 'CREDIT_NOTE' THEN -1`), so a
// second sign here would double it — and the resulting divergence would be an
// artefact of this function rather than a fact about the books, which is the
// failure mode outwardTaxable's comment warns about from the other direction.
func hsnTxval(g GSTR1) decimal.Decimal {
	t := decimal.Zero
	for _, h := range g.HSN.Data {
		t = t.Add(h.Txval)
	}
	return t
}

func hsnTax(g GSTR1) TaxTotals {
	t := zeroTax()
	for _, h := range g.HSN.Data {
		t.CGST = t.CGST.Add(h.Camt)
		t.SGST = t.SGST.Add(h.Samt)
		t.IGST = t.IGST.Add(h.Iamt)
	}
	return t
}

// ---------------------------------------------------------------------------
// DIVERGENCE MATH — the part that must not cancel
// ---------------------------------------------------------------------------

// divergence compares two sources month by month and returns the net, the
// gross, whether they offset, and the months that disagree.
//
// ⛔ GROSS IS ACCUMULATED PER MONTH AND PER HEAD, from the absolute value of
// that month's difference. Computing it as |sum| would be the same number as the
// net and would defeat the entire type. TestGrossIsNotTheAbsoluteValueOfTheNet
// pins that, and it is the mutation to try first.
func divergence(a, b string, months []Month9, pick func(Month9) (TaxTotals, TaxTotals)) Divergence {
	d := Divergence{A: a, B: b, Net: zeroTax(), Gross: zeroTax(), Agrees: true}
	for _, m := range months {
		x, y := pick(m)
		diff := subTax(x, y)
		d.Net = addTax(d.Net, diff)
		d.Gross = addTax(d.Gross, absTax(diff))
		if !isZeroTax(diff) {
			d.Months = append(d.Months, m.FP)
			d.Agrees = false
		}
	}
	d.Offsetting = !absTax(d.Net).Equal(d.Gross)
	return d
}

// taxableDivergence is the one-figure analogue of divergence, over taxable
// value. It carries the same offsetting rule for the same reason.
func taxableDivergence(a, b string, months []Month9) TaxableDivergence {
	d := TaxableDivergence{A: a, B: b, Net: decimal.Zero, Gross: decimal.Zero, Agrees: true}
	for _, m := range months {
		diff := m.R1Txval.Sub(m.R3BTxval)
		d.Net = d.Net.Add(diff)
		d.Gross = d.Gross.Add(diff.Abs())
		if !diff.IsZero() {
			d.Months = append(d.Months, m.FP)
			d.Agrees = false
		}
	}
	d.Offsetting = !d.Net.Abs().Equal(d.Gross)
	return d
}

// absTax takes the absolute value head by head. Head by head and NOT on the
// three-head total: a month that is +100 CGST and -100 SGST is two errors, not
// zero, and a total-level absolute value would call it clean.
func absTax(t TaxTotals) TaxTotals {
	return TaxTotals{CGST: t.CGST.Abs(), SGST: t.SGST.Abs(), IGST: t.IGST.Abs()}
}

