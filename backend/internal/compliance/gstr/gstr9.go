// table17 is the outward HSN summary, and it is the one table here that is
// fully DERIVED — because it is also the one that comes with its own second
// opinion.
//
// ⭐ IT IS NOT A RE-DERIVATION SMUGGLED INTO A RECONCILIATION, WHICH IS THE
// OBJECTION THAT HAD TO BE ANSWERED BEFORE IT COULD BE INCLUDED. Table 12 of
// GSTR-1 is built from `voucher_gst_line` — PER-LINE detail — while every other
// outward figure in this report comes from the AGGREGATE GST columns on
// `voucher_version`. They are two tables, two queries and two grains. Migration
// 0016 asserts the lines sum to the aggregate; HSNVsR1 is what checks that they
// do, month by month, on the caller's real data. So this table arrives already
// reconciled against the year's GSTR-1 sections, and if it did not, HSNVsR1
// would say so and `returns-and-books-disagree` would fire.
//
// ⚠️ A BLANK `hsn_sc` IS REPORTED, NOT DROPPED. An accounting-mode voucher keyed
// by hand carries no code, and the taxable value behind it is real; dropping the
// bucket would silently shrink the table until it no longer footed. GSTR-1's own
// Disclosures field carries the blank-HSN warning for the same reason.
func table17(g GSTR9) Table9 {
	// Keyed on (hsn, rate) across the whole year, exactly as the monthly table
	// 12 is keyed within a month. A map plus a sort rather than a running
	// merge, because twelve months of buckets do not arrive in a single order.
	type key struct {
		hsn  string
		rate string
	}
	agg := map[key]*Row9{}
	var order []key
	for _, m := range g.Months {
		for _, h := range m.HSN {
			k := key{h.HsnSc, h.Rt.String()}
			r, ok := agg[k]
			if !ok {
				tv := decimal.Zero
				label := h.HsnSc
				if label == "" {
					// SPELLED OUT rather than left blank on the row label: an
					// empty cell in a printed HSN table reads as a rendering
					// fault, and the reader goes looking for the code instead
					// of learning that there is not one.
					label = "(no HSN/SAC)"
				}
				r = &Row9{
					Label: label,
					Title: "at " + h.Rt.String() + "%",
					Txval: &tv,
					Tax:   zeroTax(),
				}
				agg[k] = r
				order = append(order, k)
			}
			nv := r.Txval.Add(h.Txval)
			r.Txval = &nv
			r.Tax = addTax(r.Tax, TaxTotals{CGST: h.Camt, SGST: h.Samt, IGST: h.Iamt})
		}
	}
	sort.Slice(order, func(i, j int) bool {
		if order[i].rate != order[j].rate {
			return order[i].rate < order[j].rate
		}
		return order[i].hsn < order[j].hsn
	})
	rows := make([]Row9, 0, len(order))
	for _, k := range order {
		rows = append(rows, *agg[k])
	}
	return Table9{
		No:     "17",
		Title:  "HSN-wise summary of outward supplies",
		Status: TableDerived,
		Rows:   rows,
	}
}

