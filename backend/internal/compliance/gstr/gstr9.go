// ---------------------------------------------------------------------------
// TABLE STATUS
// ---------------------------------------------------------------------------

// The three answers a GSTR-9 table can give about itself. There is deliberately
// no fourth value meaning "empty": a table with no data is DERIVED and zero,
// which is a different statement from NOT_DERIVED and must not be spelled the
// same way. That distinction is the whole point of this type.
const (
	// TableDerived — every row of this table came out of these books.
	TableDerived = "DERIVED"
	// TablePartial — some rows came out of these books and some cannot. The
	// omitted rows are listed individually, each with its own reason, and any
	// total over the whole table is suppressed.
	TablePartial = "PARTIAL"
	// TableNotDerived — nothing in this table can be produced from these books.
	// It carries NO rows, not zero rows.
	TableNotDerived = "NOT_DERIVED"
)

// Table9 is one table of the annual return, and its own account of whether it
// could be produced.
type Table9 struct {
	// No is the statutory table number ("4", "6", "17"), as a string because
	// the sub-rows are lettered and a reader matches on the printed label.
	No string `json:"no"`
	// Title is the table's statutory heading.
	Title string `json:"title"`
	// Status is TableDerived, TablePartial or TableNotDerived.
	Status string `json:"status"`
	// Reason is REQUIRED unless Status is TableDerived, and names the missing
	// input in words a filer can act on. Validate9 enforces its presence: a
	// PARTIAL or NOT_DERIVED table with no reason is a blank space on a
	// statutory form, which is the failure this whole type exists to prevent.
	Reason string `json:"reason,omitempty"`
	// Rows are the derived rows, in statutory order. Empty for NOT_DERIVED.
	Rows []Row9 `json:"rows,omitempty"`
	// Omitted names the sub-rows that could NOT be derived, each with its own
	// reason. Populated for PARTIAL; empty otherwise.
	Omitted []Omission9 `json:"omitted,omitempty"`
	// TotalSuppressed is true when this table's statutory TOTAL row cannot be
	// honestly stated because Omitted is non-empty. When it is true there is no
	// total row in Rows, and TotalSuppressedReason says why in the total's
	// place.
	TotalSuppressed bool `json:"total_suppressed,omitempty"`
	// TotalSuppressedReason is REQUIRED when TotalSuppressed is true.
	TotalSuppressedReason string `json:"total_suppressed_reason,omitempty"`
}

// Row9 is one lettered row of a table: a label, a taxable value where the row
// has one, and the three tax heads.
type Row9 struct {
	// Label is the statutory row label, e.g. "4B" or "6E".
	Label string `json:"label"`
	// Title is the row's statutory description.
	Title string `json:"title"`
	// Txval is the taxable value. Nil where the row has no taxable value (the
	// ITC tables are tax-only), and a POINTER rather than a zero for the reason
	// budget_variance.go makes VariancePercent a pointer: a zero taxable value
	// and no taxable value are different facts and must not print the same.
	Txval *decimal.Decimal `json:"txval,omitempty"`
	// Tax is the row's three heads.
	Tax TaxTotals `json:"tax"`
}

// Omission9 is one sub-row a table could not produce, and why.
type Omission9 struct {
	Label  string `json:"label"`
	Title  string `json:"title"`
	Reason string `json:"reason"`
}

// ---------------------------------------------------------------------------
// DIVERGENCE — the type that refuses to report a net alone
// ---------------------------------------------------------------------------

// Divergence is a comparison of two of the year's three sources, month by
// month, in the only form that cannot hide an offsetting pair.
//
// ⭐ READ Gross BEFORE Net. Net is what a filer would otherwise see and is the
// figure that cancels; Gross is the one that cannot. See the file header.
type Divergence struct {
	// A and B name the two sources compared, in the order the subtraction was
	// done: every figure below is A minus B.
	A string `json:"a"`
	B string `json:"b"`
	// Net is the sum over the year of (A - B), head by head. It CANCELS.
	Net TaxTotals `json:"net"`
	// Gross is the sum over the year of |A - B|, head by head. It cannot cancel
	// and is therefore the honest measure of how far apart the two sources are.
	Gross TaxTotals `json:"gross"`
	// Offsetting is true when Gross is not equal to |Net| in at least one head:
	// months disagree in opposite directions and the annual net understates the
	// disagreement. When it is true, Net MUST NOT be presented on its own.
	Offsetting bool `json:"offsetting"`
	// Months lists the FPs ("MMYYYY") where A and B disagree, in period order.
	// Empty means the two sources agree in every month of the year.
	Months []string `json:"months,omitempty"`
	// Agrees is true when the two sources agree in EVERY month. It is
	// deliberately not `Net.IsZero()`: that is exactly the question a net cannot
	// answer, and writing it that way is the defect this type exists to prevent.
	Agrees bool `json:"agrees"`
}

// ---------------------------------------------------------------------------
// THE MONTH ROW
// ---------------------------------------------------------------------------

// Month9 is one month of the year with all three sources beside each other. The
// slice always has exactly twelve entries, including months with no activity: a
// month that is missing from a list of twelve is a month nobody checked, and an
// annual return whose reader cannot tell "nil" from "nothing happened" is the
// same failure as a suppressed figure printed as zero.
type Month9 struct {
	// FP is the filing period, "MMYYYY", matching the FP the monthly returns
	// stamp on themselves.
	FP string `json:"fp"`
	// From and To are the month's inclusive bounds, "YYYY-MM-DD".
	From string `json:"from"`
	To   string `json:"to"`

	// R1Txval and R1Tax are GSTR-1's outward taxable value and tax, summed
	// across every section of that month's return (credit notes signed
	// negative, as GSTR1.TaxTotals does).
	R1Txval decimal.Decimal `json:"r1_txval"`
	R1Tax   TaxTotals       `json:"r1_tax"`
	// R3BTxval and R3BTax are GSTR-3B table 3.1(a).
	R3BTxval decimal.Decimal `json:"r3b_txval"`
	R3BTax   TaxTotals       `json:"r3b_tax"`
	// BooksOutwardTax is the sum of postings on the OUTPUT-tax ledgers for the
	// month's Sales vouchers. A third query over a third table.
	BooksOutwardTax TaxTotals `json:"books_outward_tax"`

	// R3BITCAvailable is 3B table 4(A) and R3BITCIneligible is 4(D). Their sum
	// is what invariant (I1) says must equal the input-tax postings.
	R3BITCAvailable  TaxTotals `json:"r3b_itc_available"`
	R3BITCIneligible TaxTotals `json:"r3b_itc_ineligible"`
	// BooksITCTax is the sum of postings on the INPUT-tax ledgers for the
	// month's Purchase vouchers.
	BooksITCTax TaxTotals `json:"books_itc_tax"`

	// HSNTxval and HSNTax are the month's GSTR-1 table-12 rollup, summed over
	// every (hsn, rate) bucket. They are a FOURTH independent path over the same
	// outward supplies: table 12 is built from `voucher_gst_line` — PER-LINE
	// detail — while every other outward figure here comes from the AGGREGATE
	// GST columns on `voucher_version`. Migration 0016 says the lines sum to the
	// aggregate; this is the check that they actually do, on real data, for
	// twelve months.
	HSNTxval decimal.Decimal `json:"hsn_txval"`
	HSNTax   TaxTotals       `json:"hsn_tax"`
	// HSN is the month's table-12 buckets, carried through so table 17 can be
	// rolled up across the year without re-reading anything. It is emitted on
	// the month row as well because a divergence in HSNVsR1 is only actionable
	// if the reader can see WHICH bucket moved.
	HSN []HSNItem `json:"hsn,omitempty"`

	// The three per-month verdicts, so a reader can find the month without
	// re-doing the arithmetic. Each is true when that comparison is exactly
	// zero for the month, head for head.
	R1MatchesR3B    bool `json:"r1_matches_r3b"`
	R3BMatchesBooks bool `json:"r3b_matches_books"`
	ITCMatchesBooks bool `json:"itc_matches_books"`
	HSNFootsToR1    bool `json:"hsn_foots_to_r1"`
}

// ---------------------------------------------------------------------------
// THE RETURN
// ---------------------------------------------------------------------------

// GSTR9 is the annual reconciliation for one financial year.
//
// ⚠️ The JSON key names here are this build's own and are NOT the GSTN annual
// utility's — see Disc9PortalSchemaUnverified. Nothing marshalled from this
// struct is an upload artifact.
type GSTR9 struct {
	// GSTIN of the filer.
	GSTIN string `json:"gstin,omitempty"`
	// FY is the financial year in the form Indian filers write it: "2025-26".
	FY string `json:"fy"`
	// From and To are the year's inclusive bounds, "YYYY-MM-DD".
	From string `json:"from"`
	To   string `json:"to"`

	// Months is the twelve-month grid, in period order. It is the evidence
	// behind every Divergence below, and it is emitted in full rather than
	// summarised because "which month" is the question this report exists to
	// answer.
	Months []Month9 `json:"months"`

	// OutwardR1VsR3B compares the two RETURNS with each other: what was
	// declared outward in GSTR-1 against what was declared in GSTR-3B 3.1(a).
	// A break here is a return-side inconsistency the department will see.
	OutwardR1VsR3B Divergence `json:"outward_r1_vs_r3b"`
	// OutwardR3BVsBooks compares the return against the BOOKS: 3B 3.1(a)
	// against the output-tax postings. A break here means the return and the
	// trial balance disagree about what was charged.
	OutwardR3BVsBooks Divergence `json:"outward_r3b_vs_books"`
	// OutwardR1VsBooks is the third leg. It is emitted even though it is
	// implied by the other two, because "GSTR-1 agrees with the books" is the
	// statement an accountant actually checks, and making the reader compose
	// two divergences to get it is how a reader stops checking.
	OutwardR1VsBooks Divergence `json:"outward_r1_vs_books"`
	// ITCVsBooks compares 3B table 4(A) + 4(D) against the input-tax postings —
	// invariant (I1) from gstr3b.go, tested over the year. It is a REAL check
	// and not an identity: 4(A) is re-summed from the denormalised GST columns
	// on PURCHASE voucher_versions, while the books side reads `posting` rows
	// against the named input-tax ledgers. A journal that credits an input-tax
	// ledger directly, or a purchase whose tax was posted to the wrong head,
	// breaks it.
	ITCVsBooks Divergence `json:"itc_vs_books"`

	// HSNVsR1 compares the PER-LINE GST detail against the INVOICE AGGREGATES:
	// GSTR-1 table 12 rolled up, against the same return's section totals. It is
	// the fourth independent path over the year's outward supplies and the only
	// one that reads `voucher_gst_line` — so it is what would catch a mixed-rate
	// invoice whose lines were re-stated without the aggregate following, or an
	// aggregate that moved without its lines.
	HSNVsR1 Divergence `json:"hsn_vs_r1"`

	// TaxableR1VsR3B compares TAXABLE VALUE between the two returns. It has no
	// books leg — see Disc9BooksCarryNoTaxableValue — so it is a two-way
	// comparison living in its own field rather than a third column that would
	// be silently empty.
	TaxableR1VsR3B TaxableDivergence `json:"taxable_r1_vs_r3b"`

	// Tables is the statutory table list, 4 through 19, each with its status.
	Tables []Table9 `json:"tables"`

	// Disclosures names every way this return is not filing-ready, over the
	// closed vocabulary in KnownDisclosures9, sorted and deduplicated. It is a
	// FIELD and not a doc comment for the reason gstr3b.go's Disclosures gives:
	// a frontend cannot read a doc comment, so a limitation that lives only in
	// this file cannot stop the UI presenting the return as final.
	Disclosures []string `json:"disclosures"`
}

// TaxableDivergence is the taxable-value analogue of Divergence. It is a
// separate type rather than a Divergence with a scalar, because TaxTotals is
// three heads and taxable value is one figure, and reusing the three-head type
// with two heads left zero would print two meaningless columns.
type TaxableDivergence struct {
	A          string          `json:"a"`
	B          string          `json:"b"`
	Net        decimal.Decimal `json:"net"`
	Gross      decimal.Decimal `json:"gross"`
	Offsetting bool            `json:"offsetting"`
	Months     []string        `json:"months,omitempty"`
	Agrees     bool            `json:"agrees"`
}

// Reconciled reports whether every comparison in the year agrees in every
// month. It is the single question the report answers, and it is deliberately
// built from the per-month Agrees flags rather than from the annual nets — for
// the reason the file header gives at length.
func (g GSTR9) Reconciled() bool {
	return g.OutwardR1VsR3B.Agrees && g.OutwardR3BVsBooks.Agrees &&
		g.OutwardR1VsBooks.Agrees && g.ITCVsBooks.Agrees &&
		g.HSNVsR1.Agrees && g.TaxableR1VsR3B.Agrees
}

// ---------------------------------------------------------------------------
// THE FINANCIAL YEAR
// ---------------------------------------------------------------------------

// financialYear parses and validates the [from, to] window as an Indian
// financial year and returns the starting calendar year plus the label filers
// write ("2025-26").
//
// ⛔ IT REFUSES ANYTHING ELSE. See ErrNotAFinancialYear: there is no GSTR-9 for
// an arbitrary window, and producing one would hand a filer a statutory-looking
// document for a period that does not exist.
func financialYear(from, to string) (int, string, error) {
	f, err := time.Parse("2006-01-02", from)
	if err != nil {
		return 0, "", fmt.Errorf("gstr: invalid from date %q: want YYYY-MM-DD", from)
	}
	t, err := time.Parse("2006-01-02", to)
	if err != nil {
		return 0, "", fmt.Errorf("gstr: invalid to date %q: want YYYY-MM-DD", to)
	}
	y := f.Year()
	wantFrom := time.Date(y, time.April, 1, 0, 0, 0, 0, time.UTC)
	wantTo := time.Date(y+1, time.March, 31, 0, 0, 0, 0, time.UTC)
	if !f.Equal(wantFrom) || !t.Equal(wantTo) {
		// The message names the window that WOULD work, computed from the
		// caller's own `from`, so the fix is a copy-paste rather than a lookup.
		// If `from` is itself mid-year the suggestion is the FY that CONTAINS
		// it, which is what the caller almost certainly meant.
		sy := y
		if f.Month() < time.April {
			sy = y - 1
		}
		return 0, "", fmt.Errorf("%w: %s covers %04d-04-01 to %04d-03-31, not %s to %s. "+
			"For a shorter window read the monthly GSTR-3B instead — an annual return for "+
			"a period the law does not recognise is a statutory-looking document about nothing",
			ErrNotAFinancialYear, fyLabel(sy), sy, sy+1, from, to)
	}
	return y, fyLabel(y), nil
}

// fyLabel renders the Indian financial-year label: 2025 -> "2025-26". The
// second half is TWO digits, which is how it is written on the return itself.
func fyLabel(startYear int) string {
	return fmt.Sprintf("%04d-%02d", startYear, (startYear+1)%100)
}

// monthWindow returns the inclusive bounds and the FP of month n (0-based) of
// the financial year beginning in April of startYear.
//
// The end date is computed as "first of the next month, minus a day" rather
// than from a table of month lengths, so February is right in a leap year
// without anybody having to remember that it is.
func monthWindow(startYear, n int) (from, to, fp string) {
	start := time.Date(startYear, time.April, 1, 0, 0, 0, 0, time.UTC).AddDate(0, n, 0)
	end := start.AddDate(0, 1, 0).AddDate(0, 0, -1)
	return start.Format("2006-01-02"), end.Format("2006-01-02"),
		fmt.Sprintf("%02d%04d", int(start.Month()), start.Year())
}

