def say_date(iso: str, lang: str) -> str:
    y, m, d = iso.split("-")
    if lang == "hi":
        return f"{int(d)} {HI_MONTHS[int(m)]} {y}"
    if lang == "hinglish":
        return f"{int(d)} {EN_MONTHS[int(m)]}"
    return f"{int(d)} {EN_MONTHS[int(m)]} {y}"


def derive_gst(lines, supplier_state, pos):
    """lines: [(taxable Decimal, rate Decimal)] -> (cgst, sgst, igst)."""
    intra = supplier_state == pos
    c = s = i = Decimal(0)
    for taxable, rate in lines:
        if rate == 0:
            continue
        if intra:
            half = (taxable * (rate / 2) / 100).quantize(MONEY, rounding=ROUND_HALF_UP)
            c += half
            s += half
        else:
            i += (taxable * rate / 100).quantize(MONEY, rounding=ROUND_HALF_UP)
    return c, s, i


def step(method, path, body=None, capture=None):
    st = {"method": method, "path": path}
    if body is not None:
        st["body"] = body
    if capture:
        st["capture"] = capture
    return st


def answer(text):
    return {"answer": text}


