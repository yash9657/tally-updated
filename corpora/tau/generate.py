class Book:
    def __init__(self, state="27", pan="AAACK1234A"):
        self.state = state
        self.gstin = make_gstin(state, pan)
        self.company = {"fy_start_date": FY_START, "state_code": state, "gstin": self.gstin}
        self.steps: list[dict] = []
        self.ledgers: list[dict] = []
        self.items: list[dict] = []
        self.vouchers: list[dict] = []
        self.balances: dict[str, Decimal] = {}  # ledger -> signed (Dr +)
        self.groups: dict[str, str] = {}

    # --- masters -----------------------------------------------------------
    @staticmethod
    def ledger_body(name, group, gstin="", state="", opening=None, dc="D"):
        body = {"name": name, "group_name": group, "created_by": "tau"}
        if gstin:
            body["gstin"] = gstin
        if state:
            body["state_code"] = state
        if opening:
            body["opening_balance"] = f4(opening)
            body["opening_dc"] = dc
        return body

    @staticmethod
    def ledger_canon(name, group, gstin="", state="", opening=None, dc="D"):
        op = f4(opening or 0)
        return {"name": name, "group": group, "gstin": gstin, "state_code": state,
                "opening_balance": op, "opening_dc": "" if op == "0.0000" else dc}

    def ledger(self, name, group, gstin="", state="", opening=None, dc="D"):
        self.steps.append(step("POST", "/ledgers", self.ledger_body(name, group, gstin, state, opening, dc)))
        self.ledgers.append(self.ledger_canon(name, group, gstin, state, opening, dc))
        self.groups[name] = group
        sign = Decimal(1) if dc == "D" else Decimal(-1)
        self.balances[name] = self.balances.get(name, Decimal(0)) + sign * Decimal(opening or 0)
        return name

    @staticmethod
    def item_body(name, hsn, rate, unit="Nos"):
        return {"name": name, "unit_symbol": unit, "hsn": hsn, "gst_rate_pct": str(rate), "created_by": "tau"}

    @staticmethod
    def item_canon(name, hsn, rate, unit="Nos"):
        return {"name": name, "unit": unit, "hsn": hsn, "gst_rate_pct": f4(rate)}

    def item(self, name, hsn, rate, unit="Nos"):
        self.steps.append(step("POST", "/stock-items", self.item_body(name, hsn, rate, unit)))
        self.items.append(self.item_canon(name, hsn, rate, unit))
        return name

    # --- vouchers ----------------------------------------------------------
    def apply(self, postings):
        for led, dc, amt in postings:
            sign = Decimal(1) if dc == "D" else Decimal(-1)
            self.balances[led] = self.balances.get(led, Decimal(0)) + sign * Decimal(amt)

    @staticmethod
    def canon_voucher(cls, date, postings, inventory=None, bank_dates=None):
        bank_dates = bank_dates or {}
        ps = []
        for led, dc, amt in postings:
            p = {"ledger": led, "dr_cr": dc, "amount": f4(amt)}
            if led in bank_dates:
                p["bank_date"] = bank_dates[led]
            ps.append(p)
        v = {"class": cls, "date": date, "postings": ps}
        if inventory:
            v["inventory"] = inventory
        return v

    @staticmethod
    def voucher_body(no, date, postings, gst=None, narration=""):
        body = {"voucher_date": date, "created_by": "tau",
                "postings": [{"ledger_id": "{@ledger:%s}" % led, "dr_cr": dc, "amount": f4(amt)}
                             for led, dc, amt in postings]}
        if no:
            body["voucher_no"] = no
        if narration:
            body["narration"] = narration
        if gst:
            body["gst"] = gst
        return body

    def post(self, cls, no, date, postings, gst=None, narration="", bank_dates=None):
        """Seed a voucher. Returns its canonical form (already appended)."""
        path = "/vouchers/" + cls
        self.steps.append(step("POST", path, self.voucher_body(no, date, postings, gst, narration)))
        v = self.canon_voucher(cls, date, postings, bank_dates=bank_dates)
        self.vouchers.append(v)
        self.apply(postings)
        return v

    def gst_block(self, pos, lines, tax_ledgers, hsn):
        supplier = self.state
        g = {"supplier_state_code": supplier, "place_of_supply_state_code": pos,
             "lines": [{"taxable_value": f4(t), "gst_rate_pct": str(r), "hsn": hsn} for t, r in lines]}
        if supplier == pos:
            g["cgst_ledger_id"] = "{@ledger:%s}" % tax_ledgers[0]
            g["sgst_ledger_id"] = "{@ledger:%s}" % tax_ledgers[1]
        else:
            g["igst_ledger_id"] = "{@ledger:%s}" % tax_ledgers[2]
        return g

    def gst_postings(self, kind, party, main, taxable, rate, pos, tax_ledgers):
        """Accounting-mode GST sale/purchase legs, computed here."""
        c, s, i = derive_gst([(Decimal(taxable), Decimal(rate))], self.state, pos)
        total = Decimal(taxable) + c + s + i
        party_side, other_side = ("D", "C") if kind == "sales" else ("C", "D")
        ps = [(party, party_side, total), (main, other_side, Decimal(taxable))]
        if c:
            ps.append((tax_ledgers[0], other_side, c))
            ps.append((tax_ledgers[1], other_side, s))
        if i:
            ps.append((tax_ledgers[2], other_side, i))
        return ps, (c, s, i, total)

    def sale_gst(self, no, date, party, pos, taxable, rate, hsn="998311", sales="Sales @18%"):
        ps, tax = self.gst_postings("sales", party, sales, taxable, rate, pos, OUT_TAX)
        g = self.gst_block(pos, [(Decimal(taxable), rate)], OUT_TAX, hsn)
        self.post("sales", no, date, ps, gst=g)
        return tax

    def purchase_gst(self, no, date, party, pos, taxable, rate, hsn="998311", purchase="Purchase @18%"):
        ps, tax = self.gst_postings("purchase", party, purchase, taxable, rate, pos, IN_TAX)
        g = self.gst_block(pos, [(Decimal(taxable), rate)], IN_TAX, hsn)
        self.post("purchase", no, date, ps, gst=g)
        return tax

    def expected(self, extra_ledgers=(), extra_items=(), extra_vouchers=(), replace=None, outputs=()):
        vs = [dict(v) for v in self.vouchers]
        if replace:
            for idx, v in replace.items():
                vs[idx] = v
        return {"ledgers": self.ledgers + list(extra_ledgers),
                "stock_items": self.items + list(extra_items),
                "vouchers": vs + list(extra_vouchers),
                "outputs": list(outputs)}


OUT_TAX = ("Output CGST", "Output SGST", "Output IGST")
IN_TAX = ("Input CGST", "Input SGST", "Input IGST")


def standard_book(state="27", with_bank="HDFC Bank", bank_opening=500000, cash_opening=0):
    b = Book(state=state)
    b.ledger("Sales @18%", "Sales Accounts")
    b.ledger("Purchase @18%", "Purchase Accounts")
    for n in OUT_TAX + IN_TAX:
        b.ledger(n, "Duties & Taxes")
    if with_bank:
        b.ledger(with_bank, "Bank Accounts", opening=bank_opening, dc="D")
    if cash_opening:
        # "Cash" is a company default ledger; its opening is set, not created.
        b.steps.append(step("PUT", "/ledgers/{@ledger:Cash}/opening",
                            {"opening_balance": f4(cash_opening), "opening_dc": "D", "created_by": "tau"}))
        # The judge replaces a born-with master by name, so the fixture restates
        # Cash as it will stand after the seed.
        b.ledgers.append(Book.ledger_canon("Cash", "Cash-in-Hand", opening=cash_opening, dc="D"))
        b.balances["Cash"] = Decimal(cash_opening)
    return b


