class Suite:
    def __init__(self):
        self.tasks: list[dict] = []
        self.rng = random.Random(20260928)

    def add(self, tid, family, lang, description, book, utterance, plan, expected, naive=None):
        t = {
            "id": tid,
            "family": family,
            "language": lang,
            "synthetic": True,
            "provenance": PROVENANCE,
            "description": description,
            "today": TODAY,
            "seed": {"company": book.company, "steps": book.steps},
            "utterance": utterance,
            "reference_plan": plan,
            "expected": expected,
        }
        if naive:
            t["naive_plan"] = naive
        self.tasks.append(t)


