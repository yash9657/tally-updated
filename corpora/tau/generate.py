def nlq_book(n):
    bank = BANKS[n % len(BANKS)]
    b = standard_book(with_bank=bank, bank_opening=250000 + n * 1000)
    party, pstate, pan = DEBTORS[n % len(DEBTORS)]
    b.ledger(party, "Sundry Debtors", make_gstin(pstate, pan), pstate, opening=40000 + n * 500, dc="D")
    sup, sstate, span = CREDITORS[n % len(CREDITORS)]
    b.ledger(sup, "Sundry Creditors", make_gstin(sstate, span), sstate, opening=30000 + n * 700, dc="C")
    expn, grp = EXPENSES[n % len(EXPENSES)]
    b.ledger(expn, grp)
    b.sale_gst("S-301", DATES[n % 8], party, pstate, AMOUNTS[n % len(AMOUNTS)], 18)
    b.purchase_gst("P-301", DATES[(n + 2) % 8], sup, sstate, AMOUNTS[(n + 4) % len(AMOUNTS)], 12)
    r = AMOUNTS[(n + 6) % len(AMOUNTS)] // 2
    b.post("receipt", "R-301", DATES[(n + 3) % 8], [(bank, "D", Decimal(r)), (party, "C", Decimal(r))])
    p = AMOUNTS[(n + 7) % len(AMOUNTS)] // 3
    b.post("payment", "P-302", DATES[(n + 4) % 8], [(expn, "D", Decimal(p)), (bank, "C", Decimal(p))])
    q = AMOUNTS[(n + 1) % len(AMOUNTS)] // 5
    b.post("payment", "P-303", DATES[(n + 5) % 8], [(sup, "D", Decimal(q)), (bank, "C", Decimal(q))])
    return b, bank, party, sup, expn


