def build() -> list[dict]:
    s = Suite()
    # (generator, count). Each task's language cycles en -> hi -> hinglish.
    plan = [
        (ve_sale, 12), (ve_purchase, 10), (ve_payment, 9), (ve_receipt, 9), (ve_contra, 5), (ve_journal, 5),
        (ii_sale, 18), (ii_purchase, 12),
        (bm_clear, 14), (bm_charges, 8), (bm_interest, 8),
        (gst_3b, 10), (gst_3b_after_missing, 8), (gst_1_hsn, 7),
        (lambda s_, n, l: nlq_balance(s_, n, l, "bank"), 6),
        (lambda s_, n, l: nlq_balance(s_, n, l, "debtor"), 6),
        (lambda s_, n, l: nlq_balance(s_, n, l, "creditor"), 6),
        (lambda s_, n, l: nlq_balance(s_, n, l, "expense"), 4),
        (nlq_sales_total, 4), (nlq_output_tax, 4),
        (mc_party, 12), (mc_bank, 6), (mc_item, 7),
        (guard, 10),
    ]
    # Each sub-kind starts its language rotation one step later than the last,
    # so no language is systematically the one a short sub-kind begins with.
    for k, (fn, count) in enumerate(plan):
        for n in range(count):
            fn(s, n, LANGS[(n + k) % 3])
    return s.tasks


def render(task: dict) -> str:
    return json.dumps(task, ensure_ascii=False, indent=2, sort_keys=False) + "\n"


def main(argv) -> int:
    tasks = build()
    ids = [t["id"] for t in tasks]
    assert len(ids) == len(set(ids)), "duplicate task id"
    if "--check" in argv:
        bad = 0
        for t in tasks:
            p = HERE / f"{t['id']}.json"
            if not p.exists() or p.read_text(encoding="utf-8") != render(t):
                print(f"drift: {p.name}", file=sys.stderr)
                bad += 1
        extra = {p.stem for p in HERE.glob("*.json")} - set(ids)
        for e in sorted(extra):
            print(f"stale fixture not produced by the generator: {e}.json", file=sys.stderr)
            bad += 1
        return 1 if bad else 0
    for p in HERE.glob("*.json"):
        p.unlink()
    for t in tasks:
        (HERE / f"{t['id']}.json").write_text(render(t), encoding="utf-8")
    print(f"wrote {len(tasks)} tasks")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
