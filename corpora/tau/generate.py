def item_seed(b: Book, items, supplier):
    """Seed stock: masters + an opening purchase item invoice, so a sale never
    runs the item negative (negative stock is refused by the engine)."""
    sname, sstate, span = supplier
    b.ledger(sname, "Sundry Creditors", make_gstin(sstate, span), sstate)
    lines = []
    inv = []
    for name, hsn, rate, qty, cost in items:
        b.item(name, hsn, rate)
        amt = Decimal(qty) * Decimal(cost)
        lines.append((amt, Decimal(rate)))
        inv.append({"item": name, "direction": "IN", "qty": f4(qty), "rate": f4(cost), "amount": f4(amt)})
    c, sg, i = derive_gst(lines, b.state, sstate)
    taxable = sum(a for a, _ in lines)
    ps = [(sname, "C", taxable + c + sg + i), ("Purchase @18%", "D", taxable)]
    if c:
        ps += [("Input CGST", "D", c), ("Input SGST", "D", sg)]
    if i:
        ps += [("Input IGST", "D", i)]
    body = {"voucher_no": "PUR-OPEN", "voucher_date": "2025-06-01", "created_by": "tau",
            "party_ledger_id": "{@ledger:%s}" % sname, "item_ledger_id": "{@ledger:Purchase @18%}",
            "gst": item_gst_block(b.state, sstate, IN_TAX),
            "inventory": [{"stock_item_id": "{@item:%s}" % name, "direction": "IN", "qty": f4(qty), "rate": f4(cost)}
                          for name, _, _, qty, cost in items]}
    b.steps.append(step("POST", "/vouchers/purchase", body))
    b.vouchers.append(Book.canon_voucher("purchase", "2025-06-01", ps, inventory=inv))
    b.apply(ps)


def item_gst_block(supplier_state, pos, tax):
    g = {"supplier_state_code": supplier_state, "place_of_supply_state_code": pos}
    if supplier_state == pos:
        g["cgst_ledger_id"] = "{@ledger:%s}" % tax[0]
        g["sgst_ledger_id"] = "{@ledger:%s}" % tax[1]
    else:
        g["igst_ledger_id"] = "{@ledger:%s}" % tax[2]
    return g


