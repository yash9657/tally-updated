def gst_book(n):
    b = standard_book()
    sales = []
    for k in range(3 + n % 3):
        party, pstate, pan = DEBTORS[(n + k * 5) % len(DEBTORS)]
        if party not in b.groups:
            b.ledger(party, "Sundry Debtors", make_gstin(pstate, pan), pstate)
        amt = AMOUNTS[(n * 2 + k * 3) % len(AMOUNTS)]
        rate = RATES[(n + k) % len(RATES)]
        date = DATES[(n + k) % len(DATES)]
        tax = b.sale_gst(f"S-{100 + k}", date, party, pstate, amt, rate)
        sales.append((amt, rate, pstate, tax))
    # a May sale that must NOT be counted in June
    party, pstate, pan = DEBTORS[(n + 1) % len(DEBTORS)]
    if party not in b.groups:
        b.ledger(party, "Sundry Debtors", make_gstin(pstate, pan), pstate)
    b.sale_gst("S-099", "2025-05-28", party, pstate, 99000, 18)
    # an inward supply: in GSTR-3B it is NOT an outward supply
    sup, sstate, span = CREDITORS[n % len(CREDITORS)]
    b.ledger(sup, "Sundry Creditors", make_gstin(sstate, span), sstate)
    b.purchase_gst("P-01", "2025-06-11", sup, sstate, 45000, 18)
    return b, sales


