"""Generate the W1a tau-style task suite: corpora/tau/*.json.

⛔ EVERY TASK HERE IS SYNTHETIC. The businesses, GSTINs, cheque numbers and
amounts are invented; GSTINs carry a VALID CHECKSUM so a master that validates
them accepts them, and that is the only sense in which they are "real". Each
file says so in `synthetic` and `provenance`. Nothing here was taken from a
customer's books, and nothing may be added that was.

WHAT A TASK IS. A seeded starting book (API steps, run by the Go harness), one
user utterance in English, Hindi (Devanagari) or Hinglish, and the EXPECTED
STATE of the books after a correct run — every task-owned master and every
voucher in canonical form (backend/internal/evals/tau/state.go) — plus, for a
question, the figures the answer must state.

⛔ THE EXPECTED STATE IS COMPUTED HERE, WITH PYTHON DECIMAL, AND NEVER RECORDED
FROM A RUN OF THE ENGINE. GST is derived by the same rule corpora/validate.py's
derive_tax re-derives independently (per-line HALF-UP at 4 dp, intra splits into
halves). A recorded expectation would make the reference agent's pass a
tautology; a computed one makes it a claim that the Go engine reproduces this
arithmetic to the paisa on every task.

THE REFERENCE PLAN is written per sub-kind below, by hand, against the HTTP API
— it is what a correct agent would do, not a function of the expected state. The
two meet only in the harness's judge. The NAIVE PLAN (guard tasks only) is the
write a credulous agent would make; the Go WrongAgent executes it.

Deterministic: fixed RNG seed, sorted output, stable JSON. Re-run with
    python3 corpora/tau/generate.py
and corpora/validate.py fails if the committed files drift from this script.
"""

