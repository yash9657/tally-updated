def wrap(narr: str, width: int = 36) -> tuple[str, str]:
    """Split a long narration across two physical rows, the way SBI and Kotak
    PDFs wrap the description cell. The label is the WHOLE narration; a parser
    that reads one row as one transaction loses the tail and invents a row."""
    if len(narr) <= width:
        return narr, ""
    return narr[:width], narr[width:]


def make_statement(bank: str, n: int, rng: random.Random) -> dict:
    fmt = BANK_FORMATS[bank]
    acct = "".join(str(rng.randint(0, 9)) for _ in range(fmt["acct_len"]))
    acct = str(rng.randint(1, 9)) + acct[1:]
    ifsc = fmt["ifsc"] + "0" + f"{rng.randint(0, 99999):05d}" + rng.choice("0123456789")
    ifsc = ifsc[:11]
    start = date(2025, 4 + n % 5, 1)
    end = (date(start.year, start.month + 1, 1) - timedelta(days=1))
    opening = Decimal(rng.randint(20000, 900000)) + Decimal(rng.randint(0, 99)) / 100
    bal = opening
    lines = []
    d = start
    for k in range(8 + rng.randint(0, 12)):
        d = min(end, d + timedelta(days=rng.randint(0, 3)))
        is_cr = rng.random() < 0.4
        kind = rng.choice(CR_KINDS if is_cr else DR_KINDS)
        text, ref = narration(rng, kind, bank)
        amt = Decimal(rng.choice([118, 236, 590, 1250, 2500, 4999, 8750, 12000, 25000, 47500, 88000, 120000]))
        if kind == "interest":
            amt = Decimal(rng.randint(150, 4800)) + Decimal(rng.randint(0, 99)) / 100
        if not is_cr and amt > bal:
            is_cr, kind = True, "cash_dep"
            text, ref = narration(rng, kind, bank)
        bal = bal + amt if is_cr else bal - amt
        lines.append({"date": d.isoformat(), "narration": text, "ref": ref,
                      "debit": "" if is_cr else m2(amt), "credit": m2(amt) if is_cr else "", "balance": m2(bal)})
    closing = bal
    fields = {"bank": fmt["name"], "account_number": acct, "ifsc": ifsc, "statement_from": start.isoformat(),
              "statement_to": end.isoformat(), "opening_balance": m2(opening), "closing_balance": m2(closing)}
    ds = lambda x: fmt_date(date.fromisoformat(x), fmt["date"])
    # Each format family groups digits its own way — no commas, 1,234,567.00 or
    # 12,34,567.00 — because a normaliser that only ever saw one of them is a
    # normaliser W5 will find out about in production.
    western = {"plain": m2, "western": globals()["western"], "indian": indian}[fmt["money"]]
    holder = rng.choice(BUYERS).upper()
    ev = {"account_number": acct, "ifsc": ifsc, "statement_from": ds(start.isoformat()),
          "statement_to": ds(end.isoformat()), "opening_balance": western(opening), "closing_balance": western(closing),
          "bank": fmt["name"].upper()}
    L = [f"SYNTHETIC TEST FIXTURE — NOT ISSUED BY {fmt['name'].upper()} — invented account and transactions",
         f"Statement of Account (layout family: {bank.lower()}-statement)",
         f"Account Holder: {holder}",
         f"Account No: {acct}    IFSC: {ifsc}",
         f"Statement From: {ds(start.isoformat())}  To: {ds(end.isoformat())}",
         f"Opening Balance: {western(opening)}", "", fmt["head"]]
    for k, l in enumerate(lines, 1):
        dd = ds(l["date"])
        dr = western(l["debit"]) if l["debit"] else ""
        cr = western(l["credit"]) if l["credit"] else ""
        b = western(l["balance"])
        if bank == "HDFC":
            L.append(f"{dd} | {l['narration']} | {l['ref'] or '0'} | {dd} | {dr} | {cr} | {b}")
        elif bank == "ICICI":
            L.append(f"{k} | {dd} | {dd} | {l['ref']} | {l['narration']} | {dr or '0.00'} | {cr or '0.00'} | {b}")
        elif bank == "SBI":
            head_n, tail_n = wrap(l["narration"])
            L.append(f"{dd} | {dd} | {head_n} | {l['ref']} | {dr} | {cr} | {b}")
            if tail_n:
                L.append(f" |  | {tail_n} |  |  |  | ")
        elif bank == "Axis":
            L.append(f"{dd} | {l['ref']} | {l['narration']} | {dr} | {cr} | {b} | {rng.randint(100, 999)}")
        else:
            head_n, tail_n = wrap(l["narration"])
            L.append(f"{dd} | {head_n} | {l['ref']} | {dr} | {cr} | {b}")
            if tail_n:
                L.append(f" | {tail_n} |  |  |  | ")
    L += ["", f"Closing Balance: {western(closing)}",
          "This is a system generated statement and does not require a signature. (SYNTHETIC)"]
    return {
        "id": f"bank-{bank.lower()}-{n + 1:02d}",
        "kind": "bank_statement",
        "synthetic": True,
        "provenance": PROVENANCE,
        "layout": f"{bank.lower()}-statement",
        "document": {"format": "text/plain", "text": "\n".join(L) + "\n"},
        "labels": {"fields": fields, "lines": lines},
        "evidence": ev,
    }


def build() -> list[dict]:
    rng = random.Random(1240)
    docs = [make_invoice(n, rng) for n in range(100)]
    for bank in BANK_FORMATS:
        for n in range(10):
            docs.append(make_statement(bank, n, rng))
    return docs


def render(doc: dict) -> str:
    return json.dumps(doc, ensure_ascii=False, indent=2) + "\n"


def main(argv) -> int:
    docs = build()
    if "--check" in argv:
        bad = [d["id"] for d in docs if (HERE / f"{d['id']}.json").read_text(encoding="utf-8") != render(d)]
        print("\n".join(bad) or "ok")
        return 1 if bad else 0
    for p in HERE.glob("*.json"):
        p.unlink()
    for d in docs:
        (HERE / f"{d['id']}.json").write_text(render(d), encoding="utf-8")
    print(f"wrote {len(docs)} documents")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
