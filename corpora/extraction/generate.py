LAYOUTS = ["classic-table", "compact-retail", "service-letterhead", "igst-interstate", "noisy-scan"]


def make_invoice(n: int, rng: random.Random) -> dict:
    layout = LAYOUTS[n % len(LAYOUTS)]
    sstate = rng.choice(list(STATES))
    supplier = f"{rng.choice(SUPPLIER_WORDS)} {rng.choice(SUPPLIER_TAILS)}"
    s_gstin = gstin(sstate, pan(rng))
    b2c = layout == "compact-retail" and n % 2 == 0
    if layout == "igst-interstate":
        bstate = rng.choice([s for s in STATES if s != sstate])
    elif layout == "service-letterhead" and n % 3 == 0:
        bstate = rng.choice([s for s in STATES if s != sstate])
    else:
        bstate = sstate
    buyer = rng.choice(BUYERS)
    b_gstin = "" if b2c else gstin(bstate, pan(rng))
    intra = sstate == bstate
    inv_date = date(2025, 4, 1) + timedelta(days=rng.randint(0, 150))
    inv_no = rng.choice(["INV/25-26/", "TI-", "", "GST/", "SI/2025/"]) + f"{rng.randint(1, 4999):04d}"
    date_style = rng.choice(["dmy/", "dmy-", "d-mon-y", "mon d, y", "dmy."])

    if layout == "service-letterhead":
        svc = rng.sample(SERVICES, k=1 + n % 2)
        lines = []
        for desc, sac, rate in svc:
            amt = Decimal(rng.choice([4500, 12000, 18500, 25000, 36000, 60000, 7500]))
            lines.append({"description": desc, "hsn": sac, "qty": "1", "unit": "", "rate": m2(amt),
                          "amount": m2(amt), "gst_rate_pct": str(rate)})
    else:
        goods = rng.sample(GOODS, k=1 + rng.randint(0, 4 if layout != "compact-retail" else 2))
        lines = []
        for desc, hsn, rate, unit in goods:
            qty = Decimal(rng.choice([1, 2, 5, 10, 12, 20, 25, 50, 100]))
            price = Decimal(rng.choice([45, 62.5, 110, 240, 385, 999, 1250, 2400, 5600])).quantize(Q2)
            amt = (qty * price).quantize(Q2)
            lines.append({"description": desc, "hsn": hsn, "qty": str(qty), "unit": unit, "rate": m2(price),
                          "amount": m2(amt), "gst_rate_pct": str(rate)})

    taxable = sum(Decimal(l["amount"]) for l in lines)
    c = s = i = Decimal(0)
    for l in lines:
        a, b, g = tax_line(Decimal(l["amount"]), int(l["gst_rate_pct"]), intra)
        c, s, i = c + a, s + b, i + g
    c, s, i = (x.quantize(Q2, rounding=ROUND_HALF_UP) for x in (c, s, i))
    gross = taxable + c + s + i
    rounded = gross.quantize(Decimal(1), rounding=ROUND_HALF_UP) if layout != "service-letterhead" else gross
    round_off = rounded - gross
    total = rounded

    fields = {
        "supplier_name": supplier, "supplier_gstin": s_gstin, "buyer_name": buyer, "buyer_gstin": b_gstin,
        "invoice_no": inv_no, "invoice_date": inv_date.isoformat(), "place_of_supply": bstate,
        "taxable_value": m2(taxable), "cgst": m2(c), "sgst": m2(s), "igst": m2(i),
        "round_off": m2(round_off), "invoice_total": m2(total),
    }
    ev = {}
    ds = fmt_date(inv_date, date_style)
    money = indian if layout in ("classic-table", "noisy-scan", "igst-interstate") else western

    def mv(key, val):
        txt = money(val)
        ev[key] = txt
        return txt

    # LABEL VOCABULARY VARIES PER DOCUMENT. Real invoices say "Invoice No.",
    # "Inv No", "Bill #", "Tax Invoice No." for the same field; a set that used
    # one spelling per layout would let a five-line regex score 1.0 on every
    # header, and then the set could not tell two models apart at the top.
    lab = {
        "no": rng.choice(["Invoice No.:", "Inv No:", "Invoice Number:", "Tax Invoice No.", "Bill No:", "Invoice #:"]),
        "date": rng.choice(["Dated:", "Date:", "Inv. Date:", "Invoice Dt.", "Dt:", "Date of Invoice:"]),
        "buyer": rng.choice(["Buyer (Bill to):", "Bill To:", "Billed To:", "M/s.", "Customer:", "Consignee (Ship to):"]),
        "pos": rng.choice(["Place of Supply:", "POS:", "Place Of Supply -", "State of Supply:"]),
        "taxable": rng.choice(["Taxable Value:", "Taxable Amt", "Sub-total:", "Assessable Value:", "Total Before Tax:"]),
        "total": rng.choice(["Total: ₹", "Grand Total:", "Total Amount (INR):", "Amount Payable:", "NET AMT",
                             "Total Invoice Value:"]),
        "round": rng.choice(["Round Off:", "Rounding:", "R/O", "Less/(Add) Round off:"]),
    }
    L: list[str] = [f"SYNTHETIC TEST DOCUMENT — NOT A REAL INVOICE ({layout})"]
    city = rng.choice(CITIES[sstate])
    ev["supplier_name"], ev["supplier_gstin"], ev["invoice_no"], ev["invoice_date"] = supplier, s_gstin, inv_no, ds
    ev["buyer_name"] = buyer
    if b_gstin:
        ev["buyer_gstin"] = b_gstin
    pos_txt = f"{bstate}-{STATES[bstate]}"
    # Half the retail memos print no place of supply at all, as real ones often
    # do not. The label is still the statutory fact — the buyer's state, read
    # off the buyer's GSTIN, or the supplier's own state on a B2C memo — and
    # validate.py checks it against exactly that inference.
    pos_printed = not (layout == "compact-retail" and n % 4 in (0, 1))
    if pos_printed:
        ev["place_of_supply"] = pos_txt
    pos_line = f"{lab['pos']} {pos_txt}" if pos_printed else ""
    if layout in ("classic-table", "noisy-scan", "igst-interstate"):
        side_by_side = n % 3 == 0
        shown = supplier.upper() if layout != "noisy-scan" else supplier
        ev["supplier_name"] = shown  # the surface as printed; names compare case-insensitively
        head = [shown,
                f"Plot {rng.randint(1, 250)}, MIDC Area, {city} - {rng.randint(400001, 499999)}",
                f"GSTIN/UIN: {s_gstin}   State: {STATES[sstate]}, Code: {sstate}", "", "TAX INVOICE"]
        if side_by_side:
            # Two-column header, as a PDF text layer flattens it: the invoice
            # number and the buyer arrive on the SAME physical line.
            head += [f"{lab['no']} {inv_no}    |    {lab['buyer']} {buyer}",
                     f"{lab['date']} {ds}    |    GSTIN/UIN: {b_gstin or 'Unregistered'}"]
        else:
            head += [f"{lab['no']} {inv_no}          {lab['date']} {ds}",
                     f"{lab['buyer']} {buyer}", f"GSTIN/UIN: {b_gstin}" if b_gstin else "GSTIN/UIN: Unregistered"]
        L += head + [pos_line, "", "Sl | Description of Goods | HSN/SAC | Quantity | Rate | per | Amount"]
        for k, l in enumerate(lines, 1):
            L.append(f"{k} | {l['description']} | {l['hsn']} | {l['qty']} {l['unit']} | {indian(l['rate'])} | "
                     f"{l['unit']} | {indian(l['amount'])}")
        L.append(f"{lab['taxable']} {mv('taxable_value', taxable)}")
        if intra:
            rate_txt = "/".join(sorted({f"{Decimal(l['gst_rate_pct']) / 2}%" for l in lines}))
            L.append(f"CGST @{rate_txt}: {mv('cgst', c)}")
            L.append(f"SGST @{rate_txt}: {mv('sgst', s)}")
        else:
            L.append(f"IGST: {mv('igst', i)}")
        L.append(f"{lab['round']} {mv('round_off', round_off)}")
        L.append(f"{lab['total']} {mv('invoice_total', total)}")
        L.append("E. & O.E.   This is a computer generated invoice.")
    elif layout == "compact-retail":
        L += [f"*** {supplier} ***", city, f"GSTIN {s_gstin}", "TAX INVOICE / CASH MEMO",
              f"{lab['no']}{inv_no}  {lab['date']}{ds}", f"{lab['buyer']} {buyer}" + (f"  GSTIN {b_gstin}" if b_gstin else ""),
              pos_line, "-" * 32]
        for l in lines:
            L.append(f"{l['description']} ({l['hsn']})")
            L.append(f"  {l['qty']} x {western(l['rate'])} = {western(l['amount'])}  GST{l['gst_rate_pct']}%")
        L.append("-" * 32)
        L.append(f"{lab['taxable']}   {mv('taxable_value', taxable)}")
        L.append(f"CGST      {mv('cgst', c)}")
        L.append(f"SGST      {mv('sgst', s)}")
        L.append(f"{lab['round']} {mv('round_off', round_off)}")
        L.append(f"{lab['total']}   {mv('invoice_total', total)}")
        L.append("Thank you! Visit again")
    else:  # service-letterhead
        L += [supplier, f"{city}, {STATES[sstate]} | GSTIN: {s_gstin}", "",
              f"{lab['no']} {inv_no}", f"{lab['date']} {ds}", f"{lab['buyer']} {buyer}",
              f"Client GSTIN: {b_gstin}", pos_line, "",
              "Particulars | SAC | Amount (INR) | GST Rate"]
        for l in lines:
            L.append(f"{l['description']} | {l['hsn']} | {western(l['amount'])} | {l['gst_rate_pct']}%")
        L.append(f"{lab['taxable']} {mv('taxable_value', taxable)}")
        if intra:
            L.append(f"Add: CGST {mv('cgst', c)}")
            L.append(f"Add: SGST {mv('sgst', s)}")
        else:
            L.append(f"Add: IGST {mv('igst', i)}")
        L.append(f"{lab['total']} {mv('invoice_total', total)}")
        L.append("Payment due within 30 days. Bank: details on request.")
    if layout == "noisy-scan":
        # Scan damage. Stray marks and a mangled footer everywhere; and on the
        # VALUES of two amounts the confusions OCR actually makes (0->O, 1->l,
        # 5->S). The label stays the TRUE value and the evidence records the
        # damaged surface: a model that repairs "4,5O3.OO" from context scores,
        # one that copies it does not. validate.py undoes exactly these three
        # substitutions to prove the damaged surface still means the label.
        L = [ln.replace("Description of Goods", "Descr1ption  of  Goods").replace("E. & O.E.", "E.&0.E ,")
             for ln in L]
        L.insert(3, "| . ' ~   ,  ")
        L.append("Signature ________   (seal illegible)")
        # NUMERIC fields only: a damaged "SI/2O2S" is unrecoverable in
        # principle (was it S or 5?), while a damaged total is recoverable from
        # the footing — which is exactly the reasoning a good extractor does.
        for key, label in (("invoice_total", lab["total"]), ("taxable_value", lab["taxable"])):
            surface = ev[key]
            damaged = surface.translate(str.maketrans({"0": "O", "1": "l", "5": "S"}))
            if damaged != surface:
                L = [ln.replace(surface, damaged) if ln.startswith(label) else ln for ln in L]
                ev[key] = damaged
                ev.setdefault("_ocr_damaged", []).append(key)
    return {
        "id": f"inv-{n + 1:03d}",
        "kind": "invoice",
        "synthetic": True,
        "provenance": PROVENANCE,
        "layout": layout,
        "document": {"format": "text/plain", "text": "\n".join(L) + "\n"},
        "labels": {"fields": fields, "lines": lines},
        "evidence": ev,
        "ocr_damaged": ev.pop("_ocr_damaged", []),
    }


