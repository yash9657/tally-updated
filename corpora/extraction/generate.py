"""Generate the W1a extraction set: corpora/extraction/*.json.

⛔ EVERYTHING HERE IS SYNTHETIC, AND EVERY DOCUMENT SAYS SO IN ITS FIRST LINE.
PLAN-AGENTIC W1 asks for "100 Indian invoices + 50 bank statements". We cannot
obtain 100 real invoices or any real bank statement, and inventing a provenance
for one would poison every number measured against it. So these are GENERATED:
invented businesses, invented GSTINs (checksum-valid, not issued), invented
account numbers, invented transactions. The bank layouts follow the column
headings commonly seen on statements of each bank's type (date, narration,
reference, withdrawal, deposit, balance, in that bank's typical order and date
style) — they are NOT copies of any real statement, carry no logo, and each
says "NOT ISSUED BY <BANK>" in its header. A real-document set (consented,
redacted, CA-reviewed) is OWED and is named as such in d124.

WHAT A FIXTURE IS. `document.text` — the page as an OCR engine or a PDF text
layer would hand it over — and `labels`, the field-level ground truth, plus
`evidence`: the exact surface string each header label was rendered as, so
corpora/validate.py can prove every label is GROUNDED in the text (a label
the document does not contain is a label no extractor can hit, and would
silently cap every model's recall).

Deterministic (fixed seed). Re-run with
    python3 corpora/extraction/generate.py
"""

