Q2 = Decimal("0.01")
Q4 = Decimal("0.0001")

GSTIN_CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def gstin(state: str, pan: str) -> str:
    body = f"{state}{pan}1Z"
    total = 0
    for i, c in enumerate(body):
        v = GSTIN_CHARS.index(c) * (1 if i % 2 == 0 else 2)
        total += v // 36 + v % 36
    return body + GSTIN_CHARS[(36 - total % 36) % 36]


def m2(d) -> str:
    return str(Decimal(d).quantize(Q2, rounding=ROUND_HALF_UP))


def indian(d, decimals=True) -> str:
    d = Decimal(d).quantize(Q2, rounding=ROUND_HALF_UP)
    neg = d < 0
    d = abs(d)
    whole, frac = divmod(d, 1)
    s = str(int(whole))
    if len(s) > 3:
        head, tail = s[:-3], s[-3:]
        parts = []
        while len(head) > 2:
            parts.insert(0, head[-2:])
            head = head[:-2]
        if head:
            parts.insert(0, head)
        s = ",".join(parts) + "," + tail
    out = s + (f"{frac:.2f}"[1:] if decimals else "")
    return ("-" if neg else "") + out


def western(d) -> str:
    return f"{Decimal(d).quantize(Q2, rounding=ROUND_HALF_UP):,.2f}"


