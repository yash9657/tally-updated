def fmt_date(d: date, style: str) -> str:
    return {
        "dmy/": f"{d.day:02d}/{d.month:02d}/{d.year}",
        "dmy-": f"{d.day:02d}-{d.month:02d}-{d.year}",
        "dmy.": f"{d.day:02d}.{d.month:02d}.{d.year}",
        "d-mon-y": f"{d.day:02d}-{EN_MONTH[d.month]}-{d.year}",
        "mon d, y": f"{FULL_MONTH[d.month]} {d.day}, {d.year}",
        "iso": d.isoformat(),
        "dmy2/": f"{d.day:02d}/{d.month:02d}/{d.year % 100:02d}",
        "d mon y": f"{d.day} {EN_MONTH[d.month]} {d.year}",
    }[style]


def tax_line(taxable: Decimal, rate: int, intra: bool):
    if intra:
        half = (taxable * Decimal(rate) / 2 / 100).quantize(Q4, rounding=ROUND_HALF_UP)
        return half, half, Decimal(0)
    return Decimal(0), Decimal(0), (taxable * Decimal(rate) / 100).quantize(Q4, rounding=ROUND_HALF_UP)


def pan(rng: random.Random, kind: str = "F") -> str:
    L = "ABCDEFGHJKLMNPQRSTUVWXYZ"
    return "".join(rng.choice(L) for _ in range(3)) + kind + rng.choice(L) + f"{rng.randint(1000, 9999)}" + rng.choice(L)


